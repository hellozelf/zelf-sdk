def ensure_node_modules(root: Path) -> None:
    """Install the node tooling once, so no step reaches for `npx -y`.

    Resolving openapi-typescript and prettier from the registry on every run
    costs about two and a half seconds.
    """
    root.mkdir(parents=True, exist_ok=True)
    # Write the manifest first, so a newly added tool is actually installed.
    (root / "package.json").write_text(json.dumps(PACKAGE_JSON, indent=2) + "\n")
    if (root / "node_modules" / ".bin" / "openapi-typescript").exists():
        return
    subprocess.run(["npm", "install", "--silent", "--no-audit", "--no-fund"],
                   cwd=root, check=True, capture_output=True)


def emit(api: Api, spec_path: Path, root: Path, templates: Path) -> None:
    src = root / "src"
    if src.exists():
        shutil.rmtree(src)
    (src / "resources").mkdir(parents=True)

    ensure_node_modules(root)
    subprocess.run(
        [str(root / "node_modules" / ".bin" / "openapi-typescript"),
         str(spec_path), "-o", str(src / "schema.d.ts")],
        check=True, capture_output=True, cwd=root,
    )
    for name in ("pagination.ts", "transport.ts"):
        shutil.copyfile(templates / "src" / name, src / name)
    (src / "webhooks.ts").write_text(
        webhooks_module(api, (templates / "src" / "webhooks_head.ts").read_text())
    )
    (src / "version.ts").write_text(f'{HEADER}\nexport const VERSION = "{VERSION}"\n')
    (src / "errors.ts").write_text(errors_module(api, (templates / "src" / "errors.ts").read_text()))
    (src / "models.ts").write_text(models_module(api))
    for resource, ops in sorted(api.resources.items()):
        (src / "resources" / f"{resource}.ts").write_text(resource_module(resource, ops))
    (src / "client.ts").write_text(client_module(api))
    (src / "index.ts").write_text(index_module(api))
    (root / "package.json").write_text(json.dumps(PACKAGE_JSON, indent=2) + "\n")
    # The lock records this package's own version in two places; npm rewrites
    # both on the next install, which leaves the tree dirty mid-release.
    lock_path = root / "package-lock.json"
    if lock_path.exists():
        lock = json.loads(lock_path.read_text())
        lock["version"] = VERSION
        if "" in lock.get("packages", {}):
            lock["packages"][""]["version"] = VERSION
        lock_path.write_text(json.dumps(lock, indent=2) + "\n")
    (root / "tsconfig.json").write_text(json.dumps(TSCONFIG, indent=2) + "\n")
    # This package has its own prettier config so formatting never reaches for
    # the repo-wide defaults the other client apps use.
    (root / ".prettierrc").write_text(
        json.dumps(
            {"semi": False, "singleQuote": True, "printWidth": 100, "trailingComma": "all"},
            indent=2,
        )
        + "\n"
    )
    subprocess.run(
        [str(root / "node_modules" / ".bin" / "prettier"), "--write", "--log-level", "error", "src"],
        cwd=root, capture_output=True,
    )

VERSION = version_for("js")

HEADER = "// Generated by codegen. Do not edit by hand.\n"

STATUS_CLASS = {
    400: "BadRequestError",
    401: "AuthenticationError",
    403: "PermissionDeniedError",
    404: "NotFoundError",
    406: "NotAcceptableError",
    409: "ConflictError",
    429: "RateLimitError",
    500: "InternalServerError",
    503: "ServiceUnavailableError",
}

PRIMITIVE = {"str": "string", "int": "number", "float": "number", "bool": "boolean",
             "datetime": "string | Date", "any": "unknown"}


def union(values: list[str]) -> str:
    return " | ".join(json.dumps(v) for v in values)


def ts_type(node: Type, *, in_query: bool, aliases: dict[tuple[str, ...], str] | None = None) -> str:
    if node.kind in PRIMITIVE:
        return PRIMITIVE[node.kind]
    if node.kind == "enum":
        values = tuple(node.enum or [])
        return aliases[values] if aliases and values in aliases else union(list(values))
    if node.kind == "ref":
        return node.ref or "unknown"
    if node.kind == "array":
        inner = ts_type(node.item, in_query=in_query, aliases=aliases) if node.item else "unknown"
        wrapped = f"({inner})" if "|" in inner else inner
        return f"{wrapped}[] | {wrapped}" if in_query else f"{wrapped}[]"
    return "unknown"


def enum_types(node: Type):
    if node.kind == "enum" and node.enum:
        yield tuple(node.enum)
    elif node.kind == "array" and node.item:
        yield from enum_types(node.item)


def build_aliases(ops: list[Operation]) -> dict[tuple[str, ...], str]:
    aliases: dict[tuple[str, ...], str] = {}
    taken: set[str] = set()
    for op in ops:
        for param in (*op.path_params, *op.query_params, *op.body_fields):
            for values in enum_types(param.type):
                if values in aliases:
                    continue
                name = pascal(param.name)
                if name in taken:
                    name = pascal(f"{op.method}_{param.name}")
                while name in taken:
                    name += "Value"
                aliases[values] = name
                taken.add(name)
    return aliases


def refs(node: Type) -> set[str]:
    if node.kind == "ref" and node.ref:
        return {node.ref}
    if node.kind == "array" and node.item:
        return refs(node.item)
    return set()


def jsdoc(text: str, indent: str, extra: list[str] | None = None) -> str:
    body = textwrap.wrap(" ".join(text.split()), 88) if text else []
    lines = [f"{indent}/**"]
    lines += [f"{indent} * {line}" for line in body]
    for line in extra or []:
        lines.append(f"{indent} * {line}")
    lines.append(f"{indent} */")
    return "\n".join(lines)


def options_interface(op: Operation, aliases) -> tuple[str, str]:
    params = [*op.query_params, *op.body_fields]
    if not params:
        return "", ""
    name = f"{pascal(op.resource)}{pascal(op.method)}Params"
    lines = [f"export interface {name} {{"]
    for param in params:
        if param.description:
            lines.append(jsdoc(param.description, "  "))
        rendered = ts_type(param.type, in_query=param.location == "query", aliases=aliases)
        lines.append(f"  {camel(param.name)}{'' if param.required else '?'}: {rendered}")
    lines.append("}")
    return name, "\n".join(lines)


def return_type(op: Operation) -> str:
    if op.returns_nothing:
        return "Promise<void>"
    if op.cardinality == "page":
        return f"Promise<Page<{op.item}>>"
    if op.cardinality == "list":
        return f"Promise<{op.item}[]>"
    return f"Promise<{op.item}>"


def record(params: list[Param], name: str) -> str:
    rows = ",\n".join(f"      {json.dumps(p.name)}: params.{camel(p.name)}" for p in params)
    return f"    const {name} = {{\n{rows},\n    }}"


def method(op: Operation, options_name: str) -> str:
    required = any(p.required for p in (*op.query_params, *op.body_fields))
    args = [f"{camel(p.name)}: {ts_type(p.type, in_query=False)}" for p in op.path_params]
    if options_name:
        args.append(f"params{'' if required else '?'}: {options_name}")
    args.append("options?: { signal?: AbortSignal }")

    body_text = re.sub(r"^`[a-z_.]+`\n\n", "", op.description).split("\n\n**Examples**")[0]
    lines = [
        jsdoc(
            f"{op.summary}. {body_text}" if op.summary else body_text,
            "  ",
            [f"@see `{op.operation_id}` - {op.http_method} {op.path}"],
        ),
        f"  async {camel(op.method)}({', '.join(args)}): {return_type(op)} {{",
    ]
    if options_name and not required:
        lines.append("    params ??= {}")

    parts = []
    if op.path_params:
        rows = ", ".join(f"{json.dumps(p.name)}: {camel(p.name)}" for p in op.path_params)
        parts.append(f"pathParams: {{ {rows} }}")
    if op.query_params:
        lines.append(record(op.query_params, "query"))
        parts.append("query")
    if op.body_fields:
        lines.append(record(op.body_fields, "body"))
        parts.append("body")
    parts.append("signal: options?.signal")

    item = op.item or "never"
    verb, path = json.dumps(op.http_method), json.dumps(op.path)
    request = f"this.transport.request<{item}>({verb}, {path}, {{ {', '.join(parts)} }})"

    if op.cardinality == "page":
        paged = [p if p != "query" else "query: { ...query, page }" for p in parts]
        if "query: { ...query, page }" not in paged:
            paged.insert(len(paged) - 1, "query: { page }")
        next_request = f"this.transport.request<{item}>({verb}, {path}, {{ {', '.join(paged)} }})"
        lines += [
            f"    const envelope = await {request}",
            f"    return new Page(envelope, (page) => {next_request})",
        ]
    elif op.returns_nothing:
        lines.append(f"    await {request}")
    elif op.cardinality == "list":
        lines.append(f"    return rows(await {request})")
    else:
        lines.append(f"    return one(await {request}, {json.dumps(op.item)})")
    lines.append("  }")
    return "\n".join(lines)


def resource_module(resource: str, ops: list[Operation]) -> str:
    aliases = build_aliases(ops)
    models = sorted(
        {op.item for op in ops if op.item}
        | {r for op in ops for p in (*op.query_params, *op.body_fields) for r in refs(p.type)}
    )
    helpers = sorted({"Page"} if any(o.cardinality == "page" for o in ops) else set())
    helpers += sorted(
        ({"one"} if any(o.cardinality == "single" and o.item for o in ops) else set())
        | ({"rows"} if any(o.cardinality == "list" for o in ops) else set())
    )

    out = [HEADER, "import type { Transport } from '../transport.js'"]
    if helpers:
        out.append("import { " + ", ".join(helpers) + " } from '../pagination.js'")
    if models:
        out.append("import type { " + ", ".join(models) + " } from '../models.js'")
    out.append("")
    for values, name in aliases.items():
        out.append(f"export type {name} = {union(list(values))}")
    if aliases:
        out.append("")

    bodies = []
    for op in ops:
        name, declaration = options_interface(op, aliases)
        if declaration:
            out += [declaration, ""]
        bodies.append(method(op, name))

    out += [
        f"export class {pascal(resource)}Resource {{",
        # Type stripping cannot erase a parameter property.
        "  private readonly transport: Transport",
        "",
        "  constructor(transport: Transport) {",
        "    this.transport = transport",
        "  }",
        "",
        "\n\n".join(bodies),
        "}",
        "",
    ]
    return "\n".join(out)


def errors_module(api: Api, template: str) -> str:
    out = [HEADER.rstrip(), template.rstrip(), ""]
    for status in sorted(set(STATUS_CLASS) | set(api.error_codes)):
        name = STATUS_CLASS[status]
        codes = api.error_codes.get(status)
        doc = f"/** {', '.join('`' + c + '`' for c in codes)}. */\n" if codes else ""
        out.append(
            f"{doc}export class {name} extends ZelfAPIError {{\n"
            f"  static readonly status = {status}\n}}\n"
        )
    rows = "\n".join(f"  {s}: {STATUS_CLASS[s]}," for s in sorted(STATUS_CLASS))
    out += [
        "const STATUS_MAP: Record<number, typeof ZelfAPIError> = {",
        rows,
        "}",
        "",
        "export function statusError(",
        "  status: number,",
        "  options: {",
        "    message: string",
        "    code?: string | null",
        "    details?: Record<string, unknown>",
        "    logId?: string | null",
        "    response?: Response | null",
        "  },",
        "): ZelfAPIError {",
        "  const Cls = STATUS_MAP[status] ?? ZelfAPIError",
        "  return new Cls(options.message, { ...options, status })",
        "}",
        "",
        f"export type ErrorCode = {union(sorted({c for v in api.error_codes.values() for c in v}))}",
        "",
    ]
    return "\n".join(out)


def one_line(text: str, width: int = 84) -> str:
    """First sentence of a description, cut on a word boundary."""
    flat = " ".join(re.sub(r"`|\*\*", "", text).split())
    sentence = flat.split(". ")[0].rstrip(".")
    if len(sentence) <= width:
        return sentence
    return textwrap.shorten(sentence, width=width, placeholder="...")


def webhooks_module(api: Api, template: str) -> str:
    lines = [
        "",
        "/** Event types the API can deliver, one per `webhooks` declaration. */",
        "export const EventType = {",
    ]
    for event in api.webhooks:
        lines.append(f"  /** {one_line(event.description, 86)} */")
        lines.append(f"  {pascal(event.name)}: {json.dumps(event.event_type)},")
    lines += [
        "} as const",
        "",
        "export type EventType = (typeof EventType)[keyof typeof EventType]",
        "",
        "const KNOWN: ReadonlySet<string> = new Set(Object.values(EventType))",
        "",
        "/** Whether the API declares this event type. */",
        "export function isEventType(value: string): value is EventType {",
        "  return KNOWN.has(value)",
        "}",
        "",
    ]
    marker = "export const DEFAULT_TOLERANCE_SECONDS = 300"
    head, _, tail = template.partition(marker)
    return HEADER + head + marker + "\n" + "\n".join(lines) + tail


def client_module(api: Api) -> str:
    resources = sorted(api.resources)
    out = [
        HEADER,
        "import { Transport, type ClientOptions } from './transport.js'",
    ]
    for res in resources:
        out.append(f"import {{ {pascal(res)}Resource }} from './resources/{res}.js'")
    out += [
        "",
        jsdoc(
            f"Client for the {api.title}. The key is read from `options.apiKey`, falling "
            "back to the ZELF_API_KEY environment variable. It is sent as the x-api-key "
            "header and never appears in a URL or in JSON.stringify output.",
            "",
        ),
        "export class ZelfAPIClient {",
        "  readonly transport: Transport",
    ]
    for res in resources:
        out.append(f"  readonly {camel(res)}: {pascal(res)}Resource")
    out += ["", "  constructor(options: ClientOptions = {}) {", "    this.transport = new Transport(options)"]
    for res in resources:
        out.append(f"    this.{camel(res)} = new {pascal(res)}Resource(this.transport)")
    out += [
        "  }",
        "",
        "  toJSON(): Record<string, unknown> {",
        "    return this.transport.toJSON()",
        "  }",
        "}",
        "",
    ]
    return "\n".join(out)


def models_module(api: Api) -> str:
    names = sorted(n for n, s in api.schemas.items() if not n.startswith("Paginated"))
    out = [HEADER, "import type { components } from './schema.js'", "",
           "export type { components, paths, operations } from './schema.js'", ""]
    for name in names:
        out.append(f"export type {name} = components['schemas'][{json.dumps(name)}]")
    out.append("")
    return "\n".join(out)


def index_module(api: Api) -> str:
    return "\n".join([
        HEADER,
        f"// Client for the {api.title} (spec version {api.version}).",
        "export { ZelfAPIClient } from './client.js'",
        "export { Page, rows, one, type PageMeta } from './pagination.js'",
        "export { DEFAULT_BASE_URL, type ClientOptions, type Envelope } from './transport.js'",
        "export * from './errors.js'",
        "export * from './models.js'",
        "export * as webhooks from './webhooks.js'",
        "export { VERSION } from './version.js'",
        "",
    ])



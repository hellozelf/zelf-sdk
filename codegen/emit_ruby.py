VERSION = version_for("ruby")

HEADER = "# Generated by codegen. Do not edit by hand.\n\n"

CAST = {"datetime": ":time"}


def one_line(text: str, width: int = 84) -> str:
    flat = " ".join(re.sub(r"`|\*\*", "", text).split())
    sentence = flat.split(". ")[0].rstrip(".")
    return sentence if len(sentence) <= width else textwrap.shorten(sentence, width, placeholder="...")


def comment(text: str, indent: str = "") -> list[str]:
    if not text:
        return []
    flat = re.sub(r"\s*[-*]\s+", "; ", " ".join(text.split())).lstrip("; ")
    return [f"{indent}# {line}" for line in textwrap.wrap(flat, 84)]


def cast_for(node: Type) -> str | None:
    if node.kind == "array" and node.item:
        inner = cast_for(node.item)
        return f"[{inner}]" if inner else None
    if node.kind == "ref" and node.ref:
        return node.ref
    return CAST.get(node.kind)


def models_module(api: Api) -> str:
    found, enums = model_ir.build(api)
    known = {model.name for model in found}

    out = [HEADER.rstrip(), "require_relative 'model'", "", "module Zelf", "  module Models"]
    for enum in enums:
        out += comment(enum.description or f"Accepted values for {enum.name}.", "    ")
        out.append(f"    {enum.name.upper() if False else enum.name} = [")
        out += [f"      {json.dumps(value)}," for value in enum.values]
        out += ["    ].freeze", ""]

    # Declared first so a field may reference a class defined later in the file.
    for model in found:
        out.append(f"    class {model.name} < Zelf::Model; end")
    out.append("")

    for model in found:
        out += comment(model.description or f"The {model.name} object.", "    ")
        out.append(f"    class {model.name}")
        for field in model.fields:
            out += comment(one_line(field.description), "      ")
            cast = cast_for(field.type)
            if cast and cast.strip("[]") in known:
                cast = cast.replace(cast.strip("[]"), cast.strip("[]"))
            suffix = f", cast: {cast}" if cast else ""
            out.append(f"      field :{snake(field.name)}, {json.dumps(field.name)}{suffix}")
        out += ["    end", ""]
    out += ["  end", "end", ""]
    return "\n".join(out)


def errors_module(api: Api) -> str:
    status_class = {
        400: "BadRequestError", 401: "AuthenticationError", 403: "PermissionDeniedError",
        404: "NotFoundError", 406: "NotAcceptableError", 409: "ConflictError",
        429: "RateLimitError", 500: "InternalServerError", 503: "ServiceUnavailableError",
    }
    out = [
        HEADER.rstrip(),
        "module Zelf",
        "  # Base for everything this SDK raises.",
        "  class Error < StandardError; end",
        "",
        "  # The request never produced an HTTP response.",
        "  class ConnectionError < Error; end",
        "",
        "  # The request exceeded the configured timeout.",
        "  class TimeoutError < ConnectionError; end",
        "",
        "  # An error response from the API, carrying the envelope's own fields.",
        "  class APIError < Error",
        "    attr_reader :status, :code, :details, :log_id",
        "",
        "    def initialize(message, status:, code: nil, details: nil, log_id: nil)",
        "      # The message alone says a request was refused but never which",
        "      # field or which limit, and that is the part a caller can act on.",
        "      reasons = (details || {}).map do |field, said|",
        '        "#{field}: #{said.is_a?(Array) ? said.join(\' \') : said}"',
        "      end.join(' ')",
        "      super(reasons.empty? ? message : \"#{message} #{reasons}\")",
        "      @status = status",
        "      @code = code",
        "      @details = details || {}",
        "      @log_id = log_id",
        "    end",
        "",
        "    def to_s",
        "      parts = [status.to_s, code, super].compact",
        "      log_id ? \"#{parts.join(' ')} (log_id=#{log_id})\" : parts.join(' ')",
        "    end",
        "  end",
        "",
    ]
    for status in sorted(status_class):
        codes = api.error_codes.get(status)
        if codes:
            out += comment(", ".join(codes), "  ")
        out.append(f"  class {status_class[status]} < APIError; end")
        out.append("")
    out += [
        "  # Error codes the API can return in the envelope's error.code field.",
        "  module ErrorCode",
    ]
    every = sorted({c for codes in api.error_codes.values() for c in codes})
    for code in every:
        out.append(f"    {code} = {json.dumps(code)}.freeze")
    out += [f"    ALL = [{', '.join(every)}].freeze", "  end", ""]
    out += ["  module Errors", "    STATUS_MAP = {"]
    for status in sorted(status_class):
        out.append(f"      {status} => {status_class[status]},")
    out += [
        "    }.freeze",
        "",
        "    def self.from_response(response)",
        "      body = begin",
        "        JSON.parse(response.body.to_s)",
        "      rescue StandardError",
        "        {}",
        "      end",
        "      body = {} unless body.is_a?(Hash)",
        "      detail = body['error'].is_a?(Hash) ? body['error'] : {}",
        "      status = response.code.to_i",
        "      klass = STATUS_MAP.fetch(status, APIError)",
        "      klass.new(detail['message'] || \"HTTP #{status} from the Zelf API\",",
        "                status: status, code: detail['code'],",
        "                details: detail['details'], log_id: body['log_id'])",
        "    end",
        "  end",
        "end",
        "",
    ]
    return "\n".join(out)


def method_body(op: Operation) -> list[str]:
    args = [f"{snake(p.name)}" for p in op.path_params]
    keywords = [*op.query_params, *op.body_fields]
    for param in sorted(keywords, key=lambda p: not p.required):
        args.append(f"{snake(param.name)}:" if param.required else f"{snake(param.name)}: nil")
    signature = f"({', '.join(args)})" if args else ""

    body_text = re.sub(r"^`[a-z_.]+`\n\n", "", op.description).split("\n\n**Examples**")[0]
    out = comment(f"{op.summary}. {body_text}" if op.summary else body_text, "      ")
    out += [
        "      #",
        f"      # Calls {op.http_method} {op.path} ({op.operation_id}).",
        f"      def {snake(op.method)}{signature}",
    ]
    if op.path_params:
        pairs = ", ".join(f"{json.dumps(p.name)} => {snake(p.name)}" for p in op.path_params)
        out.append(f"        path_params = {{ {pairs} }}")
    if op.query_params:
        out.append("        query = {")
        for param in op.query_params:
            out.append(f"          {json.dumps(param.name)} => {snake(param.name)},")
        out.append("        }.reject { |_, value| value.nil? }")
    if op.body_fields:
        out.append("        body = {")
        for param in op.body_fields:
            out.append(f"          {json.dumps(param.name)} => {snake(param.name)},")
        out.append("        }.reject { |_, value| value.nil? }")

    call = [f"          :{op.http_method.lower()}", f"          {json.dumps(op.path)}"]
    extras = []
    if op.path_params:
        extras.append("path_params: path_params")
    if op.query_params:
        extras.append("query: query")
    if op.body_fields:
        extras.append("body: body")
    joined = (", " + ", ".join(extras)) if extras else ""
    out.append(f"        envelope = @transport.request(:{op.http_method.lower()}, {json.dumps(op.path)}{joined})")

    model = f"Models::{op.item}" if op.item else "nil"
    if op.returns_nothing:
        out += ["        nil", "      end"]
    elif op.cardinality == "page":
        out += [
            f"        path = @transport.resolve_path({json.dumps(op.path)}.dup, "
            + ("path_params)" if op.path_params else "{})"),
            f"        Zelf::Page.new(envelope, {model}, @transport, path, "
            + ("query)" if op.query_params else "{})"),
            "      end",
        ]
    elif op.cardinality == "list":
        out += [f"        Zelf.rows(envelope, {model})", "      end"]
    else:
        out += [f"        Zelf.one(envelope, {model}, {json.dumps(op.item)})", "      end"]
    return out


def resource_module(resource: str, ops: list[Operation]) -> str:
    out = [
        HEADER.rstrip(),
        "module Zelf",
        "  module Resources",
        f"    # The {resource} endpoints.",
        f"    class {pascal(resource)}",
        "      def initialize(transport)",
        "        @transport = transport",
        "      end",
        "",
    ]
    for index, op in enumerate(sorted(ops, key=lambda o: o.method)):
        if index:
            out.append("")
        out += method_body(op)
    out += ["    end", "  end", "end", ""]
    return "\n".join(out)


def webhooks_module(api: Api, template: str) -> str:
    lines = [
        "",
        "    # Event types the API can deliver, one per `webhooks` declaration.",
        "    module EventType",
    ]
    for event in api.webhooks:
        lines += comment(one_line(event.description), "      ")
        lines.append(
            f'      {event.event_type.replace(".", "_").upper()} = '
            f"{json.dumps(event.event_type)}.freeze"
        )
    names = [e.event_type.replace(".", "_").upper() for e in api.webhooks]
    lines += [
        "",
        f"      ALL = [{', '.join(names)}].freeze",
        "",
        "      # Whether the API declares this event type.",
        "      def self.known?(value)",
        "        ALL.include?(value.to_s)",
        "      end",
        "    end",
    ]
    marker = "    DEFAULT_TOLERANCE_SECONDS = 300"
    head, _, tail = template.partition(marker)
    return HEADER + head + marker + "\n" + "\n".join(lines) + tail


def root_module(api: Api) -> str:
    resources = sorted(api.resources)
    out = [
        HEADER.rstrip(),
        "require_relative 'zelf/version'",
        "require_relative 'zelf/errors'",
        "require_relative 'zelf/model'",
        "require_relative 'zelf/models'",
        "require_relative 'zelf/transport'",
        "require_relative 'zelf/page'",
        "require_relative 'zelf/webhooks'",
    ]
    for res in resources:
        out.append(f"require_relative 'zelf/resources/{snake(res)}'")
    out += [
        "",
        f"# Ruby client for the {api.title} (spec version {api.version}).",
        "module Zelf",
        f"  # Client for the {api.title}.",
        "  #",
        "  # The key comes from the api_key: argument, falling back to the",
        "  # ZELF_API_KEY environment variable. It is sent as the x-api-key header",
        "  # and is kept out of inspect output.",
        "  class Client",
    ]
    out.append(f"    attr_reader {', '.join(':' + snake(r) for r in resources)}")
    out += [
        "",
        "    def initialize(api_key: nil, base_url: nil, timeout: 60,",
        "                   max_retries: 2, retry_writes: false, headers: {})",
        "      @transport = Transport.new(api_key: api_key, base_url: base_url, timeout: timeout,",
        "                                 max_retries: max_retries, retry_writes: retry_writes,",
        "                                 headers: headers)",
    ]
    for res in resources:
        out.append(f"      @{snake(res)} = Resources::{pascal(res)}.new(@transport)")
    out += [
        "    end",
        "",
        "    def base_url",
        "      @transport.base_url",
        "    end",
        "",
        "    def inspect",
        '      "#<Zelf::Client base_url=#{base_url.inspect} api_key=\\"***\\">"',
        "    end",
        "  end",
        "end",
        "",
    ]
    return "\n".join(out)



def emit(api: Api, spec_path: Path, root: Path, templates: Path) -> None:
    lib = root / "lib"
    if lib.exists():
        shutil.rmtree(lib)
    (lib / "zelf" / "resources").mkdir(parents=True)

    for name in ("transport.rb", "page.rb", "model.rb"):
        shutil.copyfile(templates / "lib" / "zelf" / name, lib / "zelf" / name)
    (lib / "zelf" / "version.rb").write_text(
        HEADER + f"module Zelf\n  VERSION = '{VERSION}'.freeze\nend\n"
    )
    (lib / "zelf" / "errors.rb").write_text(errors_module(api))
    (lib / "zelf" / "models.rb").write_text(models_module(api))
    (lib / "zelf" / "webhooks.rb").write_text(
        webhooks_module(api, (templates / "lib" / "zelf" / "webhooks_head.rb").read_text())
    )
    for resource, ops in sorted(api.resources.items()):
        (lib / "zelf" / "resources" / f"{snake(resource)}.rb").write_text(
            resource_module(resource, ops)
        )
    (lib / "zelf.rb").write_text(root_module(api))
    (root / "zelf.gemspec").write_text(GEMSPEC.format(title=api.title, version=VERSION))

import json
import os
import re
import shutil
import subprocess
import textwrap
from pathlib import Path

from naming import camel, go_pascal, pascal
from spec import Api, Operation
from release import version_for

VERSION = version_for("go")

HEADER = "// Generated by codegen. Do not edit by hand.\n\n"
MODULE = "github.com/hellozelf/zelf-sdk/go"

STATUS_VAR = {
    400: "ErrBadRequest",
    401: "ErrAuthentication",
    403: "ErrPermissionDenied",
    404: "ErrNotFound",
    406: "ErrNotAcceptable",
    409: "ErrConflict",
    429: "ErrRateLimit",
    500: "ErrInternalServer",
    503: "ErrServiceUnavailable",
}

OAPI_CONFIG = """package: openapi
output: {output}
generate:
  # Types only; the transport builds its own requests.
  models: true
  client: false
output-options:
  nullable-type: true
  skip-prune: true
"""


def generated_name(op: Operation) -> str:
    """Reproduce oapi-codegen's method name for an operationId.

    It title-cases each word with no initialism table, so `ai_analysis.create`
    becomes AiAnalysisCreate rather than AIAnalysisCreate.
    """
    return pascal(op.raw_operation_id.replace(".", "_"))


def doc(text: str, name: str) -> str:
    body = " ".join(re.sub(r"^`[a-z_.]+`\n\n", "", text).split("\n\n**Examples**")[0].split())
    lines = textwrap.wrap(body, 88) or [""]
    lines[0] = f"{name} {lines[0][:1].lower()}{lines[0][1:]}" if lines[0] else name
    return "\n".join(f"// {line}" for line in textwrap.wrap(" ".join(lines), 88))


def method(op: Operation, resource: str) -> str:
    receiver = f"(r *{go_pascal(resource)}Resource)"
    name = go_pascal(op.method)
    generated = generated_name(op)
    item = op.item or "struct{}"

    args = ["ctx context.Context"]
    args += [f"{camel(p.name)} string" for p in op.path_params]
    passed = ["ctx"]
    passed += [camel(p.name) for p in op.path_params]

    has_params = bool(op.query_params)
    if has_params:
        args.append(f"params *{generated}Params")
        passed.append("params")
    if op.body_fields:
        args.append(f"body {generated}JSONRequestBody")
        passed.append("body")

    if op.returns_nothing:
        result = "error"
    elif op.cardinality == "page":
        result = f"(*Page[{item}], error)"
    elif op.cardinality == "list":
        result = f"([]{item}, error)"
    else:
        result = f"(*{item}, error)"

    lines = [
        doc(op.description or op.summary, name),
        f"//",
        f"// Calls {op.http_method} {op.path} ({op.operation_id}).",
        f"func {receiver} {name}({', '.join(args)}) {result} {{",
    ]
    fail = "return nil, err" if not op.returns_nothing else "return err"
    if has_params:
        lines += [
            "\tif params == nil {",
            f"\t\tparams = &{generated}Params{{}}",
            "\t}",
        ]
    path_pairs = ", ".join(
        f"{json.dumps(p.name)}, {camel(p.name)}" for p in op.path_params
    )
    path_arg = f"[]string{{{path_pairs}}}" if op.path_params else "nil"
    params_arg = "params" if has_params else "nil"
    body_arg = "body" if op.body_fields else "nil"
    verb = json.dumps(op.http_method)
    lines += [
        f"\tenv, err := request[{item}](ctx, r.t, {verb}, {json.dumps(op.path)},",
        f"\t\t{path_arg}, {params_arg}, {body_arg})",
        "\tif err != nil {",
        f"\t\t{fail}",
        "\t}",
    ]

    if op.returns_nothing:
        lines += ["\t_ = env", "\treturn nil"]
    elif op.cardinality == "page":
        lines += [
            "\tfetch := func(ctx context.Context, page int) (*envelope[" + item + "], error) {",
            "\t\tnext := *params",
            "\t\tnext.Page = &page",
            f"\t\treturn request[{item}](ctx, r.t, {verb}, {json.dumps(op.path)},",
            f"\t\t\t{path_arg}, &next, {body_arg})",
            "\t}",
            "\treturn newPage(env, fetch), nil",
        ]
    elif op.cardinality == "list":
        lines.append("\treturn env.Results, nil")
    else:
        lines.append(f"\treturn one(env, {json.dumps(op.item)})")
    lines.append("}")
    return "\n".join(lines)


def resource_file(resource: str, ops: list[Operation]) -> str:
    name = go_pascal(resource)
    out = [
        HEADER.rstrip() + "\n",
        "package zelf\n",
        'import "context"\n',
        f"// {name}Resource groups the {resource} endpoints.",
        f"type {name}Resource struct{{ t *transport }}\n",
    ]
    out += [method(op, resource) + "\n" for op in ops]
    return "\n".join(out)


def aliases_file(api: Api, declared: set[str]) -> str:
    """Re-export every type the generator emitted.

    Aliasing only the schemas and the Params structs left the enum types those
    structs reference unreachable, so a caller could not build the params at
    all. Everything the internal package declares is part of the surface.
    """
    internal_only = {"Client", "ClientOption", "RequestEditorFn", "HttpRequestDoer"}
    names: list[str] = []
    extra = sorted(
        n
        for n in declared
        if not n.startswith("Paginated") and n not in internal_only and n[:1].isupper()
    )
    out = [
        HEADER.rstrip(),
        "",
        "package zelf",
        "",
        f'import "{MODULE}/internal/openapi"',
        "",
        "// The OpenAPI types are generated into an internal package so the",
        "// generator's own option constructors do not collide with this",
        "// package's. These aliases make them part of the public surface.",
        "type (",
    ]
    for name in [*names, *extra]:
        out.append(f"\t{name} = openapi.{name}")
    out += [")", ""]
    return "\n".join(out)


def errors_file(api: Api, template: str) -> str:
    out = [HEADER.rstrip(), template.rstrip(), "", "// Sentinel errors for errors.Is on an APIError's status.", "var ("]
    for status in sorted(STATUS_VAR):
        codes = api.error_codes.get(status)
        note = f" // {', '.join(codes)}" if codes else ""
        out.append(f'\t{STATUS_VAR[status]} = &APIError{{Status: {status}}}{note}')
    out += [")", ""]
    out += [
        "// Is lets errors.Is(err, zelf.ErrRateLimit) match on status alone.",
        "func (e *APIError) Is(target error) bool {",
        "\tother, ok := target.(*APIError)",
        "\treturn ok && other.Status == e.Status && other.Code == \"\"",
        "}",
        "",
    ]
    every = sorted({c for codes in api.error_codes.values() for c in codes})
    out += ["// Error codes the API can return in the envelope's error.code field.", "const ("]
    for code in every:
        out.append(f'\tCode{go_pascal(code)} = "{code}"')
    out += [")", ""]
    return "\n".join(out)


def one_line(text: str, width: int = 84) -> str:
    """First sentence of a description, cut on a word boundary."""
    flat = " ".join(re.sub(r"`|\*\*", "", text).split())
    sentence = flat.split(". ")[0].rstrip(".")
    if len(sentence) <= width:
        return sentence
    return textwrap.shorten(sentence, width=width, placeholder="...")


def webhooks_file(api: Api, template: str) -> str:
    lines = [
        "",
        "// EventType is an event the API can deliver, one per `webhooks`",
        "// declaration in the spec.",
        "type EventType string",
        "",
        "const (",
    ]
    for event in api.webhooks:
        name = "Event" + go_pascal(event.event_type.replace(".", "_"))
        lines.append(f"\t// {name} {one_line(event.description, 76)}")
        lines.append(f'\t{name} EventType = "{event.event_type}"')
    lines += [
        ")",
        "",
        "var knownEvents = map[EventType]bool{",
    ]
    for event in api.webhooks:
        lines.append(f'\t"{event.event_type}": true,')
    lines += [
        "}",
        "",
        "// Valid reports whether the API declares this event type.",
        "func (e EventType) Valid() bool { return knownEvents[e] }",
        "",
        "// String returns the wire value.",
        "func (e EventType) String() string { return string(e) }",
        "",
    ]
    marker = "\tDefaultTolerance = 5 * time.Minute\n)"
    head, _, tail = template.partition(marker)
    return HEADER.rstrip() + "\n" + head + marker + "\n" + "\n".join(lines) + tail


def client_file(api: Api) -> str:
    resources = sorted(api.resources)
    out = [
        HEADER.rstrip(),
        "",
        "package zelf",
        "",
        f"// Version is the SDK version sent in the User-Agent header.",
        f'const Version = "{VERSION}"',
        "",
        f"// Client is the {api.title} client. Create one with New.",
        "type Client struct {",
        "\tt *transport",
        "",
    ]
    for res in resources:
        out.append(f"\t{go_pascal(res)} *{go_pascal(res)}Resource")
    out += [
        "}",
        "",
        "// New builds a client. The API key comes from WithAPIKey, or from the",
        "// ZELF_API_KEY environment variable when that option is not given.",
        "func New(opts ...Option) (*Client, error) {",
        "\tt, err := newTransport(opts...)",
        "\tif err != nil {",
        "\t\treturn nil, err",
        "\t}",
        "\treturn &Client{",
        "\t\tt: t,",
    ]
    for res in resources:
        out.append(f"\t\t{go_pascal(res)}: &{go_pascal(res)}Resource{{t: t}},")
    out += [
        "\t}, nil",
        "}",
        "",
        "// BaseURL reports the endpoint the client talks to. The API key is",
        "// deliberately not exposed on Client.",
        "func (c *Client) BaseURL() string { return c.t.baseURL }",
        "",
    ]
    return "\n".join(out)


OAPI_CODEGEN_VERSION = "v2.5.0"


def oapi_codegen(root: Path) -> Path:
    """Install oapi-codegen once and reuse the binary.

    `go run module@version` re-resolves the module on every invocation, which
    costs over two seconds per run.
    """
    bin_dir = root.parent / ".tools" / "bin"
    binary = bin_dir / "oapi-codegen"
    if binary.exists():
        return binary
    bin_dir.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["go", "install",
         f"github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@{OAPI_CODEGEN_VERSION}"],
        check=True, capture_output=True,
        env={**os.environ, "GOBIN": str(bin_dir)},
    )
    return binary


def emit(api: Api, spec_path: Path, root: Path, templates: Path) -> None:
    import downgrade

    # Only remove what this generator wrote; hand-written tests live alongside.
    for path in root.glob("*.go"):
        if not path.name.endswith("_test.go"):
            path.unlink()
    shutil.rmtree(root / "internal", ignore_errors=True)
    (root / "internal" / "openapi").mkdir(parents=True)
    (root / "webhooks").mkdir(exist_ok=True)

    import yaml

    scratch = root / "openapi-3.0.yaml"
    scratch.write_text(yaml.safe_dump(downgrade.build(spec_path), sort_keys=False, width=10000))
    config = root / "oapi-codegen.yaml"
    config.write_text(OAPI_CONFIG.format(output="internal/openapi/openapi.gen.go"))
    subprocess.run(
        [str(oapi_codegen(root)), "-config", str(config), str(scratch)],
        check=True, capture_output=True, cwd=root,
    )
    scratch.unlink()

    for name in ("transport.go", "page.go"):
        shutil.copyfile(templates / name, root / name)
    (root / "webhooks" / "verify.go").write_text(
        webhooks_file(api, (templates / "webhooks" / "verify_head.go").read_text())
    )
    generated = (root / "internal" / "openapi" / "openapi.gen.go").read_text()
    declared = set(re.findall(r"^type (\w+)", generated, re.M))
    (root / "errors.go").write_text(errors_file(api, (templates / "errors_head.go").read_text()))
    (root / "aliases.go").write_text(aliases_file(api, declared))
    (root / "client.go").write_text(client_file(api))
    for resource, ops in sorted(api.resources.items()):
        (root / f"resource_{resource}.go").write_text(resource_file(resource, ops))
    if not (root / "go.mod").exists():
        subprocess.run(["go", "mod", "init", MODULE], cwd=root, capture_output=True)
    subprocess.run(["gofmt", "-w", "."], cwd=root, capture_output=True)
    subprocess.run(["go", "mod", "tidy"], cwd=root, capture_output=True)

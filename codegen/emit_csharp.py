def emit(api: Api, spec_path: Path, root: Path, templates: Path) -> None:
    src = root / "src"
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)

    body, aliases = models_file(api)
    (src / "Models.cs").write_text(body)
    for name in ("Transport.cs", "Page.cs"):
        shutil.copyfile(templates / name, src / name)
    (src / "Exceptions.cs").write_text(exceptions_file(api))
    (src / "Webhooks.cs").write_text(
        webhooks_file(api, (templates / "Webhooks.Head.cs").read_text())
    )
    for resource, ops in sorted(api.resources.items()):
        (src / f"{pascal(resource)}Resource.cs").write_text(resource_file(resource, ops, aliases))
    (src / "ZelfClient.cs").write_text(client_file(api))
    (src / "Zelf.csproj").write_text(CSPROJ.format(title=api.title, version=VERSION))

VERSION = version_for("csharp")

HEADER = "// Generated by codegen. Do not edit by hand.\n\n"

PRIMITIVE = {"str": "string", "int": "long", "float": "double", "bool": "bool",
             "datetime": "DateTimeOffset", "any": "JsonElement"}

STATUS_CLASS = {
    400: "ZelfBadRequestException", 401: "ZelfAuthenticationException",
    403: "ZelfPermissionDeniedException", 404: "ZelfNotFoundException",
    406: "ZelfNotAcceptableException", 409: "ZelfConflictException",
    429: "ZelfRateLimitException", 500: "ZelfInternalServerException",
    503: "ZelfServiceUnavailableException",
}

RESERVED = {"string", "int", "long", "double", "bool", "object", "class", "event",
            "operator", "params", "ref", "out", "base", "default", "lock", "new"}


def one_line(text: str, width: int = 84) -> str:
    flat = " ".join(re.sub(r"`|\*\*", "", text).split())
    sentence = flat.split(". ")[0].rstrip(".")
    return sentence if len(sentence) <= width else textwrap.shorten(sentence, width, placeholder="...")


def xmldoc(text: str, indent: str) -> list[str]:
    if not text:
        return []
    flat = re.sub(r"\s*[-*]\s+", "; ", " ".join(text.split())).lstrip("; ")
    flat = flat.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    lines = textwrap.wrap(flat, 84)
    return [f"{indent}/// <summary>"] + [f"{indent}/// {line}" for line in lines] + [f"{indent}/// </summary>"]


def member(name: str) -> str:
    out = pascal(name)
    return f"@{out}" if out.lower() in RESERVED else out


def cs_type(node: Type, aliases: dict[tuple[str, ...], str], nullable: bool,
            enum_names: frozenset[str] = frozenset()) -> str:
    if node.kind in PRIMITIVE:
        rendered = PRIMITIVE[node.kind]
    elif node.kind == "enum":
        # The wire value is the contract, and several of these sets contain
        # values like "-posted_at" that no C# identifier can hold, so the
        # accepted values ship as constants rather than an enum.
        rendered = "string"
    elif node.kind == "ref":
        rendered = "string" if node.ref in enum_names else (node.ref or "JsonElement")
    elif node.kind == "array":
        inner = cs_type(node.item, aliases, False, enum_names) if node.item else "JsonElement"
        rendered = f"IReadOnlyList<{inner}>"
    else:
        rendered = "JsonElement"
    return f"{rendered}?" if nullable else rendered


ENUM_NAMES: frozenset[str] = frozenset()


def request_models(api: Api) -> set[str]:
    """Models reachable from a request body.

    They are built by hand, so they get init-only properties rather than a
    positional constructor with 38 arguments.
    """
    roots = {op.body for op in api.operations if op.body}
    seen: set[str] = set()
    queue = list(roots)
    while queue:
        name = queue.pop()
        if name in seen or name not in api.schemas:
            continue
        seen.add(name)
        stack = [api.schemas[name]]
        while stack:
            node = stack.pop()
            if isinstance(node, dict):
                ref = node.get("$ref")
                if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
                    queue.append(ref.rsplit("/", 1)[-1])
                stack.extend(node.values())
            elif isinstance(node, list):
                stack.extend(node)
    return seen


def models_file(api: Api) -> tuple[str, dict[tuple[str, ...], str]]:
    global ENUM_NAMES
    found, enums = model_ir.build(api)
    aliases = {tuple(e.values): e.name for e in enums}
    ENUM_NAMES = frozenset(e.name for e in enums)
    for model in found:
        for field in model.fields:
            node = field.type.item if field.type.kind == "array" and field.type.item else field.type
            if node.kind == "enum" and node.enum and tuple(node.enum) not in aliases:
                aliases[tuple(node.enum)] = f"{model.name}{pascal(field.name)}"

    out = [
        HEADER.rstrip(),
        "using System.Text.Json;",
        "using System.Text.Json.Serialization;",
        "",
        "namespace Zelf;",
        "",
    ]
    for values, name in aliases.items():
        description = next((e.description for e in enums if e.name == name), "")
        out += xmldoc(description or f"Accepted values for {name}.", "")
        out.append(f"public static class {name}")
        out.append("{")
        for value in values:
            out.append(f'    public const string {enum_member(value)} = "{value}";')
        out.append("")
        joined = ", ".join(enum_member(v) for v in values)
        out.append("    /// <summary>Every value the API accepts here.</summary>")
        out.append(f"    public static readonly IReadOnlyList<string> All = [{joined}];")
        out += ["}", ""]

    built_by_hand = request_models(api)
    for model in found:
        out += xmldoc(model.description or f"The {model.name} object.", "")
        if model.name in built_by_hand:
            out.append(f"public sealed record {model.name}")
            out.append("{")
            for field in model.fields:
                out += xmldoc(one_line(field.description), "    ")
                rendered = cs_type(field.type, aliases, True, ENUM_NAMES)
                out.append(f'    [JsonPropertyName("{field.name}")]')
                out.append(f"    public {rendered} {member(field.name)} {{ get; init; }}")
                out.append("")
            out += ["}", ""]
            continue
        out.append(f"public sealed record {model.name}(")
        rows = []
        for field in model.fields:
            optional = field.nullable or not field.required
            rendered = cs_type(field.type, aliases, optional, ENUM_NAMES)
            rows.append(
                f'    [property: JsonPropertyName("{field.name}")] {rendered} {member(field.name)}'
            )
        out.append(",\n".join(rows))
        out += [");", ""]
    return "\n".join(out), aliases


def exceptions_file(api: Api) -> str:
    out = [
        HEADER.rstrip(),
        "using System.Text.Json;",
        "",
        "namespace Zelf;",
        "",
        "/// <summary>Base for everything this SDK throws.</summary>",
        "public class ZelfException(string message, Exception? inner = null)",
        "    : Exception(message, inner);",
        "",
        "/// <summary>The request never produced an HTTP response.</summary>",
        "public class ZelfConnectionException(string message, Exception? inner = null)",
        "    : ZelfException(message, inner);",
        "",
        "/// <summary>The request exceeded the configured timeout.</summary>",
        "public sealed class ZelfTimeoutException()",
        '    : ZelfConnectionException("The request to the ZelfAI API timed out.");',
        "",
        "/// <summary>An error response from the API, with the envelope's own fields.</summary>",
        "public class ZelfApiException(",
        "    string message,",
        "    int status,",
        "    string? code = null,",
        "    JsonElement? details = null,",
        "    string? logId = null,",
        "    Exception? inner = null) : ZelfException(message, inner)",
        "{",
        "    public int Status { get; } = status;",
        "",
        "    public string? Code { get; } = code;",
        "",
        "    public JsonElement? Details { get; } = details;",
        "",
        "    public string? LogId { get; } = logId;",
        "",
        "    public override string ToString() =>",
        "        LogId is null",
        '            ? $"{Status} {Code} {Message}"',
        '            : $"{Status} {Code} {Message} (log_id={LogId})";',
        "",
        "    internal static async Task<ZelfApiException> FromResponseAsync(",
        "        HttpResponseMessage response, CancellationToken cancellationToken)",
        "    {",
        "        string? code = null;",
        "        string? logId = null;",
        "        JsonElement? details = null;",
        "        var message = $\"HTTP {(int)response.StatusCode} from the ZelfAI API.\";",
        "        try",
        "        {",
        "            var raw = await response.Content.ReadAsStringAsync(cancellationToken).ConfigureAwait(false);",
        "            using var document = JsonDocument.Parse(raw);",
        "            var root = document.RootElement;",
        '            if (root.TryGetProperty("log_id", out var id))',
        "            {",
        "                logId = id.GetString();",
        "            }",
        '            if (root.TryGetProperty("error", out var error))',
        "            {",
        '                code = error.TryGetProperty("code", out var c) ? c.GetString() : null;',
        '                message = error.TryGetProperty("message", out var m) ? m.GetString() ?? message : message;',
        '                details = error.TryGetProperty("details", out var d) ? d.Clone() : null;',
        "            }",
        "        }",
        "        catch (JsonException)",
        "        {",
        "            // A gateway can answer with HTML; the status alone still classifies it.",
        "        }",
        "        var status = (int)response.StatusCode;",
        "        return status switch",
        "        {",
    ]
    for status in sorted(STATUS_CLASS):
        out.append(f"            {status} => new {STATUS_CLASS[status]}(message, status, code, details, logId),")
    out += [
        "            _ => new ZelfApiException(message, status, code, details, logId),",
        "        };",
        "    }",
        "}",
        "",
    ]
    for status in sorted(STATUS_CLASS):
        codes = api.error_codes.get(status)
        if codes:
            out += xmldoc(", ".join(codes), "")
        out += [
            f"public sealed class {STATUS_CLASS[status]}(",
            "    string message, int status, string? code = null,",
            "    JsonElement? details = null, string? logId = null)",
            "    : ZelfApiException(message, status, code, details, logId);",
            "",
        ]
    every = sorted({c for codes in api.error_codes.values() for c in codes})
    out += ["/// <summary>Error codes the API can return in the envelope.</summary>", "public static class ZelfErrorCode", "{"]
    for code in every:
        out.append(f'    public const string {pascal(code)} = "{code}";')
    out += ["}", ""]
    return "\n".join(out)


def params_record(op: Operation, aliases) -> tuple[str, str]:
    fields = [*op.query_params, *op.body_fields]
    if not fields:
        return "", ""
    name = f"{pascal(op.resource)}{pascal(op.method)}Params"
    out = xmldoc(f"Parameters for {op.operation_id}.", "")
    out.append(f"public sealed record {name}")
    out.append("{")
    for field in fields:
        out += xmldoc(one_line(field.description), "    ")
        rendered = cs_type(field.type, aliases, not field.required, ENUM_NAMES)
        required = "required " if field.required else ""
        out.append(f'    [JsonPropertyName("{field.name}")]')
        out.append(f"    public {required}{rendered} {member(field.name)} {{ get; init; }}")
        out.append("")
    out += ["}", ""]
    return name, "\n".join(out)


def query_lines(op: Operation) -> list[str]:
    if not op.query_params:
        return ["        var query = new List<KeyValuePair<string, string>>();"]
    out = ["        var query = new List<KeyValuePair<string, string>>();"]
    for param in op.query_params:
        name = member(param.name)
        wire = param.name
        node = param.type
        if node.kind == "array":
            source = f"parameters.{name}" if param.required else f"parameters.{name}"
            guard = "" if param.required else f"if (parameters.{name} is not null) "
            out.append(f"        {guard}foreach (var item in {source}!)")
            out.append("        {")
            out.append(f'            query.Add(new KeyValuePair<string, string>("{wire}", QueryValue.Format(item)));')
            out.append("        }")
        elif param.required:
            out.append(f'        query.Add(new KeyValuePair<string, string>("{wire}", QueryValue.Format(parameters.{name})));')
        else:
            out.append(f"        if (parameters.{name} is not null)")
            out.append("        {")
            out.append(f'            query.Add(new KeyValuePair<string, string>("{wire}", QueryValue.Format(parameters.{name})));')
            out.append("        }")
    return out


def method(op: Operation, params_name: str) -> str:
    item = op.item or "JsonElement"
    body_text = re.sub(r"^`[a-z_.]+`\n\n", "", op.description).split("\n\n**Examples**")[0]
    name = pascal(op.method) + "Async"

    args = [f"string {snake(p.name)}" for p in op.path_params]
    if params_name:
        args.append(f"{params_name} parameters" if any(f.required for f in (*op.query_params, *op.body_fields)) else f"{params_name}? parameters = null")
    args.append("CancellationToken cancellationToken = default")

    if op.returns_nothing:
        returns = "Task"
    elif op.cardinality == "page":
        returns = f"Task<Page<{item}>>"
    elif op.cardinality == "list":
        returns = f"Task<IReadOnlyList<{item}>>"
    else:
        returns = f"Task<{item}>"

    out = xmldoc(f"{op.summary}. {body_text}", "    ")
    out.append(f"    /// <remarks>Calls {op.http_method} {op.path} ({op.operation_id}).</remarks>")
    out.append(f"    public async {returns} {name}({', '.join(args)})")
    out.append("    {")
    if params_name and "? parameters = null" in " ".join(args):
        out.append(f"        parameters ??= new {params_name}();")
    pairs = ", ".join(f'["{p.name}"] = {snake(p.name)}' for p in op.path_params)
    resolved = (
        f'Transport.ResolvePath("{op.path}", new Dictionary<string, string> {{ {pairs} }})'
        if op.path_params
        else f'"{op.path}"'
    )
    out.append(f"        var path = {resolved};")
    out += query_lines(op) if params_name and op.query_params else ["        var query = new List<KeyValuePair<string, string>>();"]
    body_arg = "parameters" if op.body_fields else "null"
    out.append(
        f"        var envelope = await _transport.SendAsync<{item}>("
        f"HttpMethod.{op.http_method.capitalize()}, path, query, {body_arg}, cancellationToken)"
    )
    out.append("            .ConfigureAwait(false);")
    if op.returns_nothing:
        out.append("        _ = envelope;")
    elif op.cardinality == "page":
        out.append(f"        return new Page<{item}>(envelope, _transport, path, query);")
    elif op.cardinality == "list":
        out.append("        return Envelopes.Rows(envelope);")
    else:
        out.append(f'        return Envelopes.One(envelope, "{op.item}");')
    out.append("    }")
    return "\n".join(out)


def resource_file(resource: str, ops: list[Operation], aliases) -> str:
    name = pascal(resource)
    out = [
        HEADER.rstrip(),
        "using System.Globalization;",
        "using System.Text.Json;",
        "using System.Text.Json.Serialization;",
        "",
        "namespace Zelf;",
        "",
    ]
    bodies = []
    for op in sorted(ops, key=lambda o: o.method):
        params_name, declaration = params_record(op, aliases)
        if declaration:
            out.append(declaration)
        bodies.append(method(op, params_name))

    out += [
        f"/// <summary>The {resource} endpoints.</summary>",
        f"public sealed class {name}Resource(Transport transport)",
        "{",
        "    private readonly Transport _transport = transport;",
        "",
    ]
    out += [
        "\n\n".join(bodies),
        "}",
        "",
    ]
    return "\n".join(out)


def webhooks_file(api: Api, template: str) -> str:
    out = [
        HEADER.rstrip(),
        "namespace Zelf.Webhooks;",
        "",
        "/// <summary>An event the API can deliver, one per webhooks declaration.</summary>",
        "public enum EventType",
        "{",
    ]
    for event in api.webhooks:
        out += xmldoc(one_line(event.description), "    ")
        out.append(f"    {pascal(event.name)},")
    out += ["}", "", "/// <summary>Maps event types to and from their wire values.</summary>", "public static class EventTypes", "{"]
    out.append("    private static readonly Dictionary<string, EventType> ByWire = new()")
    out.append("    {")
    for event in api.webhooks:
        out.append(f'        ["{event.event_type}"] = EventType.{pascal(event.name)},')
    out += ["    };", ""]
    out.append("    /// <summary>The wire value for an event type.</summary>")
    out.append("    public static string ToWire(this EventType value) => value switch")
    out.append("    {")
    for event in api.webhooks:
        out.append(f'        EventType.{pascal(event.name)} => "{event.event_type}",')
    out += [
        "        _ => throw new ArgumentOutOfRangeException(nameof(value)),",
        "    };",
        "",
        "    /// <summary>The declared event type, or null for one the SDK predates.</summary>",
        "    public static EventType? FromWire(string value) =>",
        "        ByWire.TryGetValue(value, out var found) ? found : null;",
        "",
        "    /// <summary>Every event type the API declares.</summary>",
        "    public static IReadOnlyCollection<string> All => ByWire.Keys;",
        "}",
        "",
    ]
    head, _, tail = template.partition("namespace Zelf.Webhooks;")
    generated = "\n".join(out[2:])  # drop the duplicated header and namespace
    return HEADER + head + "namespace Zelf.Webhooks;\n\n" + generated + tail.lstrip("\n")


def client_file(api: Api) -> str:
    resources = sorted(api.resources)
    out = [
        HEADER.rstrip(),
        "namespace Zelf;",
        "",
        f"/// <summary>Client for the {api.title}.</summary>",
        "/// <remarks>",
        "/// The key comes from <see cref=\"ZelfClientOptions.ApiKey\"/>, falling back to",
        "/// the ZELF_API_KEY environment variable. It is sent as the x-api-key header",
        "/// and never appears in ToString output.",
        "/// </remarks>",
        "public sealed class ZelfClient : IDisposable",
        "{",
        '    /// <summary>The SDK version sent in the User-Agent header.</summary>',
        '    public const string Version = "' + VERSION + '";',
        "",
        "    private readonly Transport _transport;",
        "",
        "    public ZelfClient(ZelfClientOptions options)",
        "    {",
        "        _transport = new Transport(options);",
    ]
    for res in resources:
        out.append(f"        {pascal(res)} = new {pascal(res)}Resource(_transport);")
    out += [
        "    }",
        "",
        "    public ZelfClient(string apiKey)",
        "        : this(new ZelfClientOptions { ApiKey = apiKey })",
        "    {",
        "    }",
        "",
    ]
    for res in resources:
        out.append(f"    /// <summary>The {res} endpoints.</summary>")
        out.append(f"    public {pascal(res)}Resource {pascal(res)} {{ get; }}")
        out.append("")
    out += [
        "    /// <summary>The endpoint this client talks to.</summary>",
        "    public string BaseUrl => _transport.BaseUrl;",
        "",
        "    public override string ToString() => $\"ZelfClient(BaseUrl={BaseUrl}, ApiKey=***)\";",
        "",
        "    public void Dispose() => _transport.Dispose();",
        "}",
        "",
    ]
    return "\n".join(out)



HEADER = "# Generated by codegen. Do not edit by hand.\n"

STATUS_CLASS = {
    400: "BadRequestError",
    401: "AuthenticationError",
    403: "PermissionDeniedError",
    404: "NotFoundError",
    406: "NotAcceptableError",
    409: "ConflictError",
    429: "RateLimitError",
    500: "InternalServerError",
    503: "ServiceUnavailableError",
}

PRIMITIVE = {"str": "str", "int": "int", "float": "float", "bool": "bool",
             "datetime": "datetime", "any": "Any"}


def literal(values: list[str]) -> str:
    return "Literal[" + ", ".join(json.dumps(v) for v in values) + "]"


def py_type(node: Type, *, in_query: bool, aliases: dict[tuple[str, ...], str] | None = None) -> str:
    if node.kind in PRIMITIVE:
        return PRIMITIVE[node.kind]
    if node.kind == "enum":
        values = tuple(node.enum or [])
        if aliases and values in aliases:
            return aliases[values]
        return literal(list(values))
    if node.kind == "ref":
        return f"{node.ref} | dict[str, Any]"
    if node.kind == "array":
        inner = py_type(node.item, in_query=in_query, aliases=aliases) if node.item else "Any"
        # Query arrays repeat the key, so a lone value is the common case.
        return f"list[{inner}] | {inner}" if in_query and "|" not in inner else f"list[{inner}]"
    return "Any"


def enum_types(node: Type):
    if node.kind == "enum" and node.enum:
        yield tuple(node.enum)
    elif node.kind == "array" and node.item:
        yield from enum_types(node.item)


def build_aliases(ops: list[Operation]) -> dict[tuple[str, ...], str]:
    """Hoist every enum into a named alias.

    Inlining them produces 400-character signatures where the same long union
    is spelled twice, once for the list form and once for the scalar form.
    """
    aliases: dict[tuple[str, ...], str] = {}
    taken: set[str] = set()
    for op in ops:
        for param in (*op.path_params, *op.query_params, *op.body_fields):
            for values in enum_types(param.type):
                if values in aliases:
                    continue
                name = pascal(param.name)
                if name in taken:
                    name = pascal(f"{op.method}_{param.name}")
                while name in taken:
                    name += "Value"
                aliases[values] = name
                taken.add(name)
    return aliases


def refs(node: Type) -> set[str]:
    if node.kind == "ref" and node.ref:
        return {node.ref}
    if node.kind == "array" and node.item:
        return refs(node.item)
    return set()


def summary_line(param: Param) -> str:
    text = re.sub(r"\s+", " ", re.sub(r"`|\*\*", "", param.description)).strip()
    sentence = text.split(". ")[0].rstrip(".")
    return (sentence[:150] + "...") if len(sentence) > 150 else sentence


def docstring(op: Operation, params: list[Param], indent: str) -> str:
    lines = [op.summary or op.operation_id, ""]
    body = re.sub(r"^`[a-z_.]+`\n\n", "", op.description).strip()
    if body:
        lines += textwrap.wrap(re.sub(r"\s+", " ", body.split("\n\n**Examples**")[0]), 84)
        lines.append("")
    documented = [p for p in params if p.description]
    if documented:
        lines.append("Args:")
        for param in documented:
            text = summary_line(param)
            if text:
                lines += textwrap.wrap(
                    f"{py_param(param.name)}: {text}.", 84,
                    initial_indent="    ", subsequent_indent="        ",
                )
        lines.append("")
    lines.append(f"Calls `{op.http_method} {op.path}` (`{op.operation_id}`).")
    rendered = "\n".join((indent + line).rstrip() for line in lines)
    return f'{indent}"""{rendered.lstrip()}\n{indent}"""'


def signature(op: Operation, params: list[Param], aliases) -> list[str]:
    out = ["self"]
    for param in op.path_params:
        out.append(f"{py_param(param.name)}: {py_type(param.type, in_query=False, aliases=aliases)}")
    optional = [p for p in params if p.location != "path"]
    if optional:
        out.append("*")
    for param in optional:
        rendered = py_type(param.type, in_query=param.location == "query", aliases=aliases)
        if param.required:
            out.append(f"{py_param(param.name)}: {rendered}")
        else:
            out.append(f"{py_param(param.name)}: {rendered} | NotGiven = NOT_GIVEN")
    return out


def mapping(params: list[Param], indent: str) -> str:
    if not params:
        return "{}"
    rows = "".join(f'{indent}    "{p.name}": {py_param(p.name)},\n' for p in params)
    return "{\n" + rows + indent + "}"


def return_type(op: Operation, prefix: str) -> str:
    if op.returns_nothing:
        return "None"
    if op.cardinality == "page":
        return f"{prefix}Page[{op.item}]"
    if op.cardinality == "list":
        return f"list[{op.item}]"
    return str(op.item)


def method(op: Operation, aliases, *, is_async: bool) -> str:
    params = [*op.path_params, *op.query_params, *op.body_fields]
    names = [py_param(p.name) for p in params]
    if len(names) != len(set(names)):
        duplicates = sorted({n for n in names if names.count(n) > 1})
        raise ValueError(f"{op.operation_id}: parameters collide in Python: {duplicates}")
    prefix = "Async" if is_async else ""
    kw, aw = ("async def", "await ") if is_async else ("def", "")

    args = signature(op, params, aliases)
    head = f"    {kw} {op.method}({', '.join(args)}) -> {return_type(op, prefix)}:"
    if len(head) > 96:
        joined = ",\n        ".join(args)
        head = f"    {kw} {op.method}(\n        {joined},\n    ) -> {return_type(op, prefix)}:"

    lines = [head, docstring(op, params, "        ")]
    call = ['"' + op.http_method + '"', f'"{op.path}"']
    if op.path_params:
        call.append(f"path_params={mapping(op.path_params, '            ')}")
    if op.query_params:
        lines.append(f"        query = given({mapping(op.query_params, '        ')})")
        call.append("query=query")
    if op.body_fields:
        lines.append(f"        payload = body({mapping(op.body_fields, '        ')})")
        call.append("payload=payload" if False else "body=payload")

    request = f"{aw}self._transport.request({', '.join(call)})"

    if op.cardinality == "page":
        page_call = [c for c in call if not c.startswith("query=")] + ['query={**query, "page": page}']
        lines += [
            f"        {kw} fetch(page: int) -> dict[str, Any]:",
            f"            return {aw}self._transport.request({', '.join(page_call)})",
            "",
            f"        envelope = {request}",
            f"        return {prefix}Page(envelope, {op.item}, fetch)",
        ]
    elif op.returns_nothing:
        lines.append(f"        {request}")
    elif op.cardinality == "list":
        lines.append(f"        return rows({request}, {op.item})")
    else:
        lines.append(f"        return one({request}, {op.item})")
    return "\n".join(lines)


def resource_module(resource: str, ops: list[Operation]) -> str:
    aliases = build_aliases(ops)
    models = sorted({op.item for op in ops if op.item} | {r for op in ops for p in (*op.query_params, *op.body_fields) for r in refs(p.type)})
    needs_literal = bool(aliases)
    needs_datetime = any(
        "datetime" in py_type(p.type, in_query=p.location == "query", aliases=aliases)
        for op in ops for p in (*op.path_params, *op.query_params, *op.body_fields)
    )
    typing_names = ["Any"] + (["Literal"] if needs_literal else [])
    helpers = sorted({"one" if any(o.cardinality == "single" and o.item for o in ops) else "",
                      "rows" if any(o.cardinality == "list" for o in ops) else "",
                      "Page" if any(o.cardinality == "page" for o in ops) else "",
                      "AsyncPage" if any(o.cardinality == "page" for o in ops) else ""} - {""})
    type_helpers = sorted({"NOT_GIVEN", "NotGiven", "given"} |
                          ({"body"} if any(o.body_fields for o in ops) else set()))

    out = [HEADER, "from __future__ import annotations", ""]
    if needs_datetime:
        out.append("from datetime import datetime")
    out += [
        f"from typing import {', '.join(typing_names)}",
        "",
    ]
    if models:
        out.append(f"from .._models import {', '.join(models)}")
    if helpers:
        out.append(f"from .._pagination import {', '.join(helpers)}")
    out += [
        "from .._transport import AsyncTransport, SyncTransport",
        f"from .._types import {', '.join(type_helpers)}",
        "",
    ]
    for values, name in aliases.items():
        out.append(f"{name} = {literal(list(values))}")
    out += [
        "",
        "",
        f"class {pascal(resource)}Resource:",
        "    def __init__(self, transport: SyncTransport) -> None:",
        "        self._transport = transport",
        "",
    ]
    out += ["\n".join([method(op, aliases, is_async=False), ""]) for op in ops]
    out += [
        "",
        f"class Async{pascal(resource)}Resource:",
        "    def __init__(self, transport: AsyncTransport) -> None:",
        "        self._transport = transport",
        "",
    ]
    out += ["\n".join([method(op, aliases, is_async=True), ""]) for op in ops]
    return "\n".join(out)


def exceptions_module(api: Api, template: str) -> str:
    out = [HEADER.rstrip(), template.rstrip(), "", ""]
    for status in sorted(set(STATUS_CLASS) | set(api.error_codes)):
        name = STATUS_CLASS[status]
        codes = api.error_codes.get(status)
        doc = f'    """{", ".join("`" + c + "`" for c in codes)}."""\n' if codes else ""
        out.append(f"class {name}(ZelfAPIError):\n{doc}\n    status_code = {status}\n")
    out.append(
        "class EmptyResultError(NotFoundError):\n"
        '    """A single-object read matched nothing. The API returns 200 with an\n'
        '    empty `results` array instead of a 404, so the SDK raises this."""\n'
    )
    mapping_rows = "".join(f"    {s}: {STATUS_CLASS[s]},\n" for s in sorted(STATUS_CLASS))
    out.append("STATUS_MAP: dict[int, type[ZelfAPIError]] = {\n" + mapping_rows + "}")
    every = sorted({c for codes in api.error_codes.values() for c in codes})
    out.append(f"\nErrorCode = {literal(every)}")
    return "\n".join(out)


def one_line(text: str, width: int = 84) -> str:
    """First sentence of a description, cut on a word boundary."""
    flat = " ".join(re.sub(r"`|\*\*", "", text).split())
    sentence = flat.split(". ")[0].rstrip(".")
    if len(sentence) <= width:
        return sentence
    return textwrap.shorten(sentence, width=width, placeholder="...")


def webhooks_module(api: Api, template: str) -> str:
    lines = [
        "",
        "class EventType(str, Enum):",
        '    """Event types the API can deliver, one per `webhooks` declaration."""',
        "",
    ]
    for event in api.webhooks:
        summary = one_line(event.description)
        lines.append(f"    # {summary}")
        lines.append(f'    {event.event_type.replace(".", "_").upper()} = "{event.event_type}"')
    lines += [
        "",
        "    @classmethod",
        "    def known(cls, value: str) -> bool:",
        '        """Whether the API declares this event type."""',
        "        return value in cls._value2member_map_",
        "",
        "    def __str__(self) -> str:",
        "        return self.value",
        "",
    ]
    marker = "DEFAULT_TOLERANCE_SECONDS = 300"
    head, _, tail = template.partition(marker)
    return HEADER + head + marker + "\n\n" + "\n".join(lines) + tail


def client_module(api: Api) -> str:
    resources = sorted(api.resources)
    out = [
        HEADER,
        "from __future__ import annotations",
        "",
        "import os",
        "from collections.abc import Mapping",
        "from typing import Any",
        "",
        "import httpx",
        "",
        "from ._transport import AsyncTransport, SyncTransport",
    ]
    for res in resources:
        out.append(
            f"from .resources.{res} import {pascal(res)}Resource, Async{pascal(res)}Resource"
        )
    out += [
        "",
        f'DEFAULT_BASE_URL = "{api.server}"',
        'BASE_URL_ENV = "ZELF_BASE_URL"',
        "",
        "",
        "def default_base_url() -> str:",
        '    """The explicit argument wins, then ZELF_BASE_URL, then the production API."""',
        "    return os.environ.get(BASE_URL_ENV) or DEFAULT_BASE_URL",
        'API_KEY_ENV = "ZELF_API_KEY"',
        "",
        "",
    ]
    for flavour, transport, closer in (
        ("ZelfAPIClient", "SyncTransport", "    def close(self) -> None:\n        self._transport.close()\n\n    def __enter__(self) -> \"ZelfAPIClient\":\n        return self\n\n    def __exit__(self, *_: Any) -> None:\n        self.close()"),
        ("ZelfAPIClientAsync", "AsyncTransport", "    async def close(self) -> None:\n        await self._transport.close()\n\n    async def __aenter__(self) -> \"ZelfAPIClientAsync\":\n        return self\n\n    async def __aexit__(self, *_: Any) -> None:\n        await self.close()"),
    ):
        is_async = flavour.endswith("Async")
        client_type = "httpx.AsyncClient" if is_async else "httpx.Client"
        prefix = "Async" if is_async else ""
        doc = (
            f'    """{"Asynchronous" if is_async else "Synchronous"} client for the {api.title}.\n\n'
            f"    The key is read from the `api_key` argument, falling back to the\n"
            f"    `{{API_KEY_ENV}}` environment variable. It is sent as the `x-api-key`\n"
            f"    header and is kept out of `repr()` output.\n"
            f'    """'.replace("{API_KEY_ENV}", "ZELF_API_KEY")
        )
        out += [
            f"class {flavour}:",
            doc,
            "",
            "    def __init__(",
            "        self,",
            "        api_key: str | None = None,",
            "        *,",
            "        base_url: str | None = None,",
            "        timeout: float = 60.0,",
            "        max_retries: int = 2,",
            "        retry_writes: bool = False,",
            "        default_headers: Mapping[str, str] | None = None,",
            f"        http_client: {client_type} | None = None,",
            "    ) -> None:",
            f"        self._transport = {transport}(",
            "            api_key or os.environ.get(API_KEY_ENV, ''),",
            "            base_url=base_url or default_base_url(),",
            "            timeout=timeout,",
            "            max_retries=max_retries,",
            "            retry_writes=retry_writes,",
            "            default_headers=default_headers,",
            "            http_client=http_client,",
            "        )",
        ]
        for res in resources:
            out.append(f"        self.{res} = {prefix}{pascal(res)}Resource(self._transport)")
        out += [
            "",
            "    def __repr__(self) -> str:",
            f"        return f\"{flavour}(base_url={{self._transport.base_url!r}}, api_key='***')\"",
            "",
            closer,
            "",
            "",
        ]
    out += [
        "# The earlier name for the asynchronous client; both are the same class.",
        "AsyncZelfAPIClient = ZelfAPIClientAsync",
        "",
    ]
    return "\n".join(out)


def init_module(api: Api, model_names: list[str]) -> str:
    resources = sorted(api.resources)
    exported = [
        "ZelfAPIClient", "ZelfAPIClientAsync", "AsyncZelfAPIClient",
        "Page", "AsyncPage", "Envelope", "EventType", "WebhookEvent", "WebhookHandler",
        "NOT_GIVEN", "NotGiven", "ZelfError", "ZelfAPIError", "ZelfConnectionError",
        "ZelfTimeoutError", "ResponseParseError", "ErrorCode", *STATUS_CLASS.values(),
        "webhooks", *model_names,
    ]
    return "\n".join([
        HEADER,
        f'"""Python client for the {api.title} (spec version {api.version})."""',
        "",
        "from . import webhooks",
        "from ._client import AsyncZelfAPIClient, ZelfAPIClient, ZelfAPIClientAsync",
        "from ._exceptions import (",
        "    ErrorCode,",
        *[f"    {name}," for name in sorted(STATUS_CLASS.values())],
        "    ResponseParseError,",
        "    ZelfAPIError,",
        "    ZelfConnectionError,",
        "    ZelfError,",
        "    ZelfTimeoutError,",
        ")",
        f"from ._models import {', '.join(model_names)}",
        "from ._pagination import AsyncPage, Envelope, Page",
        "from .webhooks import EventType, WebhookEvent, WebhookHandler",
        "from ._types import NOT_GIVEN, NotGiven",
        "from ._version import __version__",
        "",
        "__all__ = [",
        *[f'    "{name}",' for name in sorted(set(exported))],
        '    "__version__",',
        "]",
        "",
    ])


def generate_models(spec_path: Path, out: Path) -> list[str]:
    import models_input

    from datamodel_code_generator import DataModelType, InputFileType, PythonVersion, generate
    from datamodel_code_generator.format import Formatter

    scratch = out.parent / "_models_input.json"
    scratch.write_text(json.dumps(models_input.build(spec_path)))
    generate(
        scratch,
        input_file_type=InputFileType.JsonSchema,
        output=out,
        output_model_type=DataModelType.PydanticV2BaseModel,
        target_python_version=PythonVersion.PY_313,
        use_standard_collections=True,
        use_union_operator=True,
        use_schema_description=True,
        field_constraints=True,
        use_annotated=True,
        enum_field_as_literal="all",
        collapse_root_models=True,
        use_double_quotes=True,
        disable_timestamp=True,
        allow_extra_fields=True,
        formatters=[Formatter.RUFF_FORMAT],
    )
    scratch.unlink()
    text = out.read_text()
    # The synthetic document root has no fields and no callers.
    text = re.sub(r"\n\nclass Model\(RootModel\[Any\]\):\n    root: Any\n", "\n", text)
    if "RootModel" not in text.replace("from pydantic import", ""):
        text = text.replace(", RootModel", "").replace("RootModel, ", "")
    out.write_text(HEADER + text.split("\n", 2)[2] if text.startswith("# generated") else text)
    return sorted(re.findall(r"^class (\w+)\(BaseModel\):", out.read_text(), re.M))



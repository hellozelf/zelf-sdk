def format_package(root: Path) -> None:
    for args in (["format"], ["check", "--fix", "--quiet"]):
        subprocess.run(["uv", "run", "ruff", *args, "zelf"], cwd=root, capture_output=True)


def emit(api: Api, spec_path: Path, root: Path, templates: Path) -> None:
    package = root / "zelf"
    if package.exists():
        shutil.rmtree(package)
    (package / "resources").mkdir(parents=True)

    for name in ("_pagination.py", "_transport.py", "_types.py"):
        shutil.copyfile(templates / "zelf" / name, package / name)
    (package / "webhooks.py").write_text(
        webhooks_module(api, (templates / "zelf" / "webhooks_head.py").read_text())
    )
    (package / "py.typed").write_text("")
    (package / "_version.py").write_text(f'{HEADER}\n__version__ = "{VERSION}"\n')

    model_names = generate_models(spec_path, package / "_models.py")
    (package / "_exceptions.py").write_text(
        exceptions_module(api, (templates / "zelf" / "_exceptions_head.py").read_text()) + "\n"
    )
    for resource, ops in sorted(api.resources.items()):
        (package / "resources" / f"{resource}.py").write_text(resource_module(resource, ops))
    (package / "resources" / "__init__.py").write_text(HEADER)
    (package / "_client.py").write_text(client_module(api))
    (package / "__init__.py").write_text(init_module(api, model_names))
    (root / "pyproject.toml").write_text(PYPROJECT.format(title=api.title, version=VERSION))
    format_package(root)

HEADER = "// Generated by codegen. Do not edit by hand.\n\n"

PRIMITIVE = {"str": "String", "int": "i64", "float": "f64", "bool": "bool",
             "datetime": "String", "any": "serde_json::Value"}

RUST_KEYWORDS = {
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false",
    "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
    "pub", "ref", "return", "self", "static", "struct", "super", "trait", "true",
    "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract",
    "become", "box", "do", "final", "macro", "override", "priv", "typeof",
    "unsized", "virtual", "yield", "try",
}


def one_line(text: str, width: int = 84) -> str:
    flat = " ".join(re.sub(r"`|\*\*", "", text).split())
    sentence = flat.split(". ")[0].rstrip(".")
    return sentence if len(sentence) <= width else textwrap.shorten(sentence, width, placeholder="...")


def field_name(name: str) -> str:
    out = snake(name)
    return f"r#{out}" if out in RUST_KEYWORDS else out


def doc(text: str, indent: str = "") -> list[str]:
    if not text:
        return []
    flat = " ".join(re.sub(r"\s+", " ", text).split())
    # Strip markdown bullets: wrapping turns their continuation lines into what
    # rustdoc reads as new, badly indented list items.
    flat = re.sub(r"\s*[-*]\s+", "; ", flat).lstrip("; ")
    return [f"{indent}/// {line}" for line in textwrap.wrap(flat, 88)]


def rust_type(node: Type, aliases: dict[tuple[str, ...], str]) -> str:
    if node.kind in PRIMITIVE:
        return PRIMITIVE[node.kind]
    if node.kind == "enum":
        values = tuple(node.enum or [])
        return aliases.get(values, "String")
    if node.kind == "ref":
        return node.ref or "serde_json::Value"
    if node.kind == "array":
        return f"Vec<{rust_type(node.item, aliases) if node.item else 'serde_json::Value'}>"
    return "serde_json::Value"


def enum_block(name: str, values: list[str], description: str) -> str:
    out = doc(description or f"Values accepted for {name}.")
    out += [
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]",
        f"pub enum {name} {{",
    ]
    for value in values:
        out.append(f'    #[serde(rename = "{value}")]')
        out.append(f"    {enum_member(value)},")
    out += ["}", ""]
    out += [f"impl {name} {{", "    /// The wire value.", "    pub fn as_str(&self) -> &'static str {", "        match self {"]
    for value in values:
        out.append(f'            {name}::{enum_member(value)} => "{value}",')
    out += ["        }", "    }", "}", ""]
    out += [
        f"impl std::fmt::Display for {name} {{",
        "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {",
        "        f.write_str(self.as_str())",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


def models_module(api: Api) -> tuple[str, dict[tuple[str, ...], str]]:
    found, enums = model_ir.build(api)
    aliases = {tuple(e.values): e.name for e in enums}
    # Enums declared inline on a property need a name of their own.
    for model in found:
        for field in model.fields:
            node = field.type.item if field.type.kind == "array" and field.type.item else field.type
            if node.kind == "enum" and node.enum and tuple(node.enum) not in aliases:
                aliases[tuple(node.enum)] = f"{model.name}{pascal(field.name)}"

    out = [HEADER.rstrip(), "use serde::{Deserialize, Serialize};", ""]
    named: dict[str, list[str]] = {}
    for values, name in aliases.items():
        description = next((e.description for e in enums if e.name == name), "")
        named[name] = list(values)
        out.append(enum_block(name, list(values), description))

    for model in found:
        out += doc(model.description or f"The {model.name} object.")
        out += [
            "#[derive(Debug, Clone, Serialize, Deserialize)]",
            f"pub struct {model.name} {{",
        ]
        for field in model.fields:
            out += doc(field.description, "    ")
            rendered = rust_type(field.type, aliases)
            optional = field.nullable or not field.required
            if optional:
                rendered = f"Option<{rendered}>"
            attrs = []
            if field_name(field.name) != field.name:
                attrs.append(f'rename = "{field.name}"')
            if optional:
                attrs.append("default")
                attrs.append('skip_serializing_if = "Option::is_none"')
            elif field.type.kind == "array":
                attrs.append("default")
            if attrs:
                out.append(f"    #[serde({', '.join(attrs)})]")
            out.append(f"    pub {field_name(field.name)}: {rendered},")
        out += ["}", ""]
    return "\n".join(out), aliases


def params_struct(op: Operation, aliases) -> tuple[str, str]:
    fields = [*op.query_params, *op.body_fields]
    if not fields:
        return "", ""
    name = f"{pascal(op.resource)}{pascal(op.method)}Params"
    out = doc(f"Parameters for {op.operation_id}.")
    # Default is only sound when nothing is required; a required enum or nested
    # object has no meaningful zero value.
    derives = (
        "Debug, Clone, Default, Serialize, Deserialize"
        if all(not f.required for f in fields)
        else "Debug, Clone, Serialize, Deserialize"
    )
    out += [f"#[derive({derives})]", f"pub struct {name} {{"]
    for field in fields:
        out += doc(field.description, "    ")
        rendered = rust_type(field.type, aliases)
        renamed = field_name(field.name)
        if renamed != field.name:
            out.append(f'    #[serde(rename = "{field.name}")]')
        if not field.required:
            rendered = f"Option<{rendered}>"
            out.append('    #[serde(skip_serializing_if = "Option::is_none")]')
        out.append(f"    pub {renamed}: {rendered},")
    out += ["}", ""]
    return name, "\n".join(out)


def push_query(param, aliases) -> list[str]:
    name = field_name(param.name)
    wire = param.name
    node = param.type
    inner = node.item if node.kind == "array" and node.item else node

    def render(expr: str) -> str:
        if inner.kind == "bool":
            return f'if *{expr} {{ "true" }} else {{ "false" }}.to_string()'
        return f"{expr}.to_string()"

    if node.kind == "array":
        body = f'for entry in value {{ query.push(("{wire}".to_string(), {render("entry")})); }}'
    else:
        body = f'query.push(("{wire}".to_string(), {render("value")}));'
    if param.required:
        bind = f"let value = &params.{name};"
        return [f"    {{ {bind} {body} }}"]
    return [f"    if let Some(value) = &params.{name} {{ {body} }}"]


def method(op: Operation, params_name: str, aliases) -> str:
    item = op.item or "serde_json::Value"
    body_text = re.sub(r"^`[a-z_.]+`\n\n", "", op.description).split("\n\n**Examples**")[0]

    args = ["&self"]
    args += [f"{field_name(p.name)}: &str" for p in op.path_params]
    if params_name:
        args.append(f"params: {params_name}")

    if op.returns_nothing:
        returns = "Result<()>"
    elif op.cardinality == "page":
        returns = f"Result<Page<{item}>>"
    elif op.cardinality == "list":
        returns = f"Result<Vec<{item}>>"
    else:
        returns = f"Result<{item}>"

    out = doc(f"{op.summary}. {body_text}" if op.summary else body_text)
    out += [
        "///",
        f"/// Calls `{op.http_method} {op.path}` (`{op.operation_id}`).",
        f"    pub async fn {snake(op.method)}({', '.join(args)}) -> {returns} {{".lstrip(),
    ]
    out = [f"    {line}" if not line.startswith("    pub async") else line for line in out]
    out = ["    " + line if line.startswith("///") else line for line in out]

    lines = [f"    pub async fn {snake(op.method)}({', '.join(args)}) -> {returns} {{"]
    lines.append("        #[allow(unused_mut)]")
    lines.append("        let mut query: Vec<(String, String)> = Vec::new();")
    for param in op.query_params:
        lines += ["    " + row for row in push_query(param, aliases)]
    path_args = ", ".join(f'("{p.name}", {field_name(p.name)})' for p in op.path_params)
    lines.append(f"        let path_params = [{path_args}];")
    if op.body_fields:
        lines.append("        let body = Some(serde_json::to_value(&params).map_err(|source| {")
        lines.append("            crate::error::Error::Decode { status: 0, source }")
        lines.append("        })?);")
    else:
        lines.append("        let body = None;")
    lines.append(
        f'        let envelope: Envelope<{item}> = self.transport'
    )
    lines.append(
        f'            .request(Method::{op.http_method}, "{op.path}", &path_params, &query, body)'
    )
    lines.append("            .await?;")

    if op.returns_nothing:
        lines += ["        let _ = envelope;", "        Ok(())"]
    elif op.cardinality == "page":
        lines.append(
            f'        Ok(Page::new(envelope, self.transport.clone(), self.transport.url("{op.path}", &path_params)?, query))'
        )
        lines[-1] = (
            f'        let path = self.transport.resolve_path("{op.path}", &path_params)?;\n'
            f"        Ok(Page::new(envelope, self.transport.clone(), path, query))"
        )
    elif op.cardinality == "list":
        lines.append("        Ok(envelope.results)")
    else:
        lines.append(f'        one(envelope, "{op.item}")')
    lines.append("    }")

    header = doc(f"{op.summary}. {body_text}" if op.summary else body_text, "    ")
    header += ["    ///", f"    /// Calls `{op.http_method} {op.path}` (`{op.operation_id}`)."]
    return "\n".join(header + lines)


def resource_module(resource: str, ops: list[Operation], aliases) -> str:
    name = pascal(resource)
    def refs(node: Type) -> set[str]:
        if node.kind == "ref" and node.ref:
            return {node.ref}
        if node.kind == "array" and node.item:
            return refs(node.item)
        return set()

    models_used = sorted(
        {op.item for op in ops if op.item}
        | {r for op in ops for p in (*op.query_params, *op.body_fields) for r in refs(p.type)}
    )
    enums_used = sorted(
        {
            aliases[tuple(node.enum)]
            for op in ops
            for p in (*op.query_params, *op.body_fields)
            for node in [p.type.item if p.type.kind == "array" and p.type.item else p.type]
            if node.kind == "enum" and node.enum and tuple(node.enum) in aliases
        }
    )
    imports = sorted(set(models_used) | set(enums_used))

    page_helpers = sorted(
        ({"Page"} if any(o.cardinality == "page" for o in ops) else set())
        | ({"one"} if any(o.cardinality == "single" and o.item for o in ops) else set())
    )
    needs_serialize = any(o.query_params or o.body_fields for o in ops)

    out = [
        HEADER.rstrip(),
        "use std::sync::Arc;",
        "",
        "use reqwest::Method;",
    ]
    if needs_serialize:
        out.append("use serde::{Deserialize, Serialize};")
    out += [
        "",
        "use crate::error::Result;",
    ]
    if page_helpers:
        out.append(f"use crate::page::{{{', '.join(page_helpers)}}};")
    out.append("use crate::transport::{Envelope, Transport};")
    if imports:
        out.append(f"use crate::models::{{{', '.join(imports)}}};")
    out.append("")

    structs = []
    bodies = []
    for op in sorted(ops, key=lambda o: o.method):
        params_name, declaration = params_struct(op, aliases)
        if declaration:
            structs.append(declaration)
        bodies.append(method(op, params_name, aliases))

    out += structs
    out += [
        f"/// The {resource} endpoints.",
        "#[derive(Debug, Clone)]",
        f"pub struct {name}Resource {{",
        "    pub(crate) transport: Arc<Transport>,",
        "}",
        "",
        f"impl {name}Resource {{",
        "\n\n".join(bodies),
        "}",
        "",
    ]
    return "\n".join(out)


def webhooks_module(api: Api, template: str) -> str:
    lines = [
        "",
        "/// An event the API can deliver, one per `webhooks` declaration in the spec.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]",
        "pub enum EventType {",
    ]
    for event in api.webhooks:
        lines += doc(one_line(event.description, 86), "    ")
        lines.append(f'    #[serde(rename = "{event.event_type}")]')
        lines.append(f"    {pascal(event.name)},")
    lines += ["}", "", "impl EventType {", "    /// The wire value.", "    pub fn as_str(&self) -> &'static str {", "        match self {"]
    for event in api.webhooks:
        lines.append(f'            EventType::{pascal(event.name)} => "{event.event_type}",')
    lines += ["        }", "    }", ""]
    lines += [
        "    /// The declared event type for a wire value, or `None` for one this",
        "    /// SDK predates.",
        "    pub fn from_wire(value: &str) -> Option<Self> {",
        "        match value {",
    ]
    for event in api.webhooks:
        lines.append(f'            "{event.event_type}" => Some(EventType::{pascal(event.name)}),')
    lines += ["            _ => None,", "        }", "    }", "}", ""]
    lines += [
        "impl std::fmt::Display for EventType {",
        "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {",
        "        f.write_str(self.as_str())",
        "    }",
        "}",
        "",
    ]
    marker = "pub const DEFAULT_TOLERANCE_SECONDS: i64 = 300;"
    head, _, tail = template.partition(marker)
    return HEADER + head + marker + "\n" + "\n".join(lines) + tail


def lib_module(api: Api) -> str:
    resources = sorted(api.resources)
    out = [
        HEADER.rstrip(),
        f"//! Rust client for the {api.title} (spec version {api.version}).",
        "//!",
        "//! ```no_run",
        "//! # async fn run() -> zelf::Result<()> {",
        '//! let client = zelf::Client::builder().api_key("...").build()?;',
        "//! let page = client",
        "//!     .content()",
        "//!     .list(zelf::resources::content::ContentListParams {",
        '//!         search: Some("running shoes".into()),',
        "//!         ..Default::default()",
        "//!     })",
        "//!     .await?;",
        "//! for item in &page.results {",
        "//!     println!(\"{}\", item.id);",
        "//! }",
        "//! # Ok(())",
        "//! # }",
        "//! ```",
        "",
        "pub mod error;",
        "pub mod models;",
        "pub mod page;",
        "pub mod transport;",
        "pub mod webhooks;",
        "",
    ]
    out.append("pub mod resources;")
    out += [
        "",
        "pub use error::{render_details, Error, Result};",
        "pub use models::*;",
        "pub use page::{Limits, Page};",
        "pub use transport::{ClientBuilder, API_KEY_ENV, DEFAULT_BASE_URL};",
        "",
        '/// The SDK version sent in the User-Agent header.',
        f'pub const VERSION: &str = "{VERSION}";',
        "",
        "use std::sync::Arc;",
        "",
        "use transport::Transport;",
        "",
    ]
    for res in resources:
        out.append(f"use resources::{snake(res)}::{pascal(res)}Resource;")
    out += [
        "",
        f"/// Client for the {api.title}.",
        "///",
        "/// The key comes from [`ClientBuilder::api_key`], falling back to the",
        "/// `ZELF_API_KEY` environment variable. It is sent as the `x-api-key`",
        "/// header and never appears in `Debug` output.",
        "#[derive(Debug, Clone)]",
        "pub struct Client {",
        "    transport: Arc<Transport>,",
        "}",
        "",
        "impl Client {",
        "    /// Start building a client.",
        "    pub fn builder() -> ClientBuilder {",
        "        ClientBuilder::default()",
        "    }",
        "",
        "    /// Build a client with the default settings and the given key.",
        "    pub fn new(api_key: impl Into<String>) -> Result<Self> {",
        "        Self::builder().api_key(api_key).build()",
        "    }",
        "",
        "    /// The endpoint this client talks to.",
        "    pub fn base_url(&self) -> &str {",
        "        &self.transport.base_url",
        "    }",
        "",
    ]
    for res in resources:
        out += [
            f"    /// The {res} endpoints.",
            f"    pub fn {snake(res)}(&self) -> {pascal(res)}Resource {{",
            f"        {pascal(res)}Resource {{ transport: self.transport.clone() }}",
            "    }",
            "",
        ]
    out += [
        "}",
        "",
        "impl ClientBuilder {",
        "    /// Finish building. Fails when no API key is configured.",
        "    pub fn build(self) -> Result<Client> {",
        "        Ok(Client { transport: self.into_transport()? })",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)



def emit(api: Api, spec_path: Path, root: Path, templates: Path) -> None:
    src = root / "src"
    if src.exists():
        shutil.rmtree(src)
    src.mkdir(parents=True)

    body, aliases = models_module(api)
    (src / "models.rs").write_text(body)
    for name in ("error.rs", "page.rs", "transport.rs"):
        shutil.copyfile(templates / "src" / name, src / name)
    (src / "webhooks.rs").write_text(
        webhooks_module(api, (templates / "src" / "webhooks_head.rs").read_text())
    )
    resources = src / "resources"
    resources.mkdir()
    for resource, ops in sorted(api.resources.items()):
        (resources / f"{snake(resource)}.rs").write_text(resource_module(resource, ops, aliases))
    (resources / "mod.rs").write_text(
        HEADER
        + "\n".join(f"pub mod {snake(name)};" for name in sorted(api.resources))
        + "\n"
    )
    (src / "lib.rs").write_text(lib_module(api))
    (root / "Cargo.toml").write_text(CARGO.format(title=api.title, version=VERSION))
    # The lock pins this crate too. Left behind, the first cargo command in CI
    # rewrites it, and `cargo publish` refuses to publish a dirty tree.
    lock = root / "Cargo.lock"
    if lock.exists():
        lock.write_text(
            re.sub(
                r'(?m)^(name = "zelf-sdk"\nversion = ")[^"]*"',
                rf'\g<1>{VERSION}"',
                lock.read_text(),
            )
        )
    subprocess.run(["cargo", "fmt"], cwd=root, capture_output=True)

UNION_METHOD = re.compile(r"^func \(t (\w+)\) As(\w+)\(\)", re.M)


GO_NAMED_TYPE = re.compile(r"^type (\w+) (\w+)$", re.M)


def go_union_tests(root: Path) -> str:
    """One round trip per oneOf field oapi-codegen turned into a union type.

    The spec's IR flattens a multi-member oneOf to `any`, so the union types are
    discovered from the emitted source instead.
    """
    generated = root / "internal" / "openapi" / "openapi.gen.go"
    if not generated.exists():
        return ""
    source = generated.read_text()
    unions: dict[str, list[str]] = {}
    for owner, variant in UNION_METHOD.findall(source):
        unions.setdefault(owner, []).append(variant)
    if not unions:
        return ""

    # A variant is a named type over a scalar, and its zero literal has to
    # match: a numeric enum does not accept "".
    underlying = dict(GO_NAMED_TYPE.findall(source))

    def zero(variant: str) -> str:
        kind = underlying.get(variant, "string")
        if kind.startswith(("int", "uint")):
            return "0"
        if kind.startswith("float"):
            return "0"
        if kind == "bool":
            return "false"
        return '""'

    body = [
        "",
        "// Every oneOf field must survive a round trip through each of its variants.",
        "func TestConformanceUnionRoundTrip(t *testing.T) {",
    ]
    for owner, variants in sorted(unions.items()):
        for variant in sorted(set(variants)):
            name = f"{owner}/{variant}"
            body += [
                f"\tt.Run({literal(name)}, func(t *testing.T) {{",
                f"\t\tvar value {owner}",
                f"\t\tif err := value.From{variant}({variant}({zero(variant)})); err != nil {{",
                "\t\t\tt.Fatalf(\"from: %v\", err)",
                "\t\t}",
                f"\t\tif _, err := value.As{variant}(); err != nil {{",
                "\t\t\tt.Errorf(\"as: %v\", err)",
                "\t\t}",
                f"\t\tif err := value.Merge{variant}({variant}({zero(variant)})); err != nil {{",
                "\t\t\tt.Errorf(\"merge: %v\", err)",
                "\t\t}",
                "\t\tencoded, err := value.MarshalJSON()",
                "\t\tif err != nil {",
                "\t\t\tt.Fatalf(\"marshal: %v\", err)",
                "\t\t}",
                f"\t\tvar again {owner}",
                "\t\tif err := again.UnmarshalJSON(encoded); err != nil {",
                "\t\t\tt.Errorf(\"unmarshal: %v\", err)",
                "\t\t}",
                "\t})",
            ]
    body.append("}")
    return "\n".join(body) + "\n"


def go_strings(values: list[str]) -> str:
    if not values:
        return "nil"
    return "[]string{" + ", ".join(literal(v) for v in values) + "}"


def go_query(values: dict[str, list[str]]) -> str:
    if not values:
        return "nil"
    pairs = ", ".join(
        literal(name) + ": {" + ", ".join(literal(v) for v in rendered) + "}"
        for name, rendered in values.items()
    )
    return "map[string][]string{" + pairs + "}"


def pascal_operation(operation: Operation) -> str:
    from naming import pascal

    return pascal(operation.raw_operation_id.replace(".", "_"))



def literal(value) -> str:
    """A JSON literal, which is also valid in every C-family language here."""
    return json.dumps(value)


def py_literal(value) -> str:
    if value is True:
        return "True"
    if value is False:
        return "False"
    if value is None:
        return "None"
    if isinstance(value, list):
        return "[" + ", ".join(py_literal(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{json.dumps(k)}: {py_literal(v)}" for k, v in value.items()) + "}"
    return json.dumps(value)


def sample_for(param: Param, registry: dict):
    value = samples.sample(param.type, "Request", param.name, registry, frozenset())
    if param.type.kind == "array" and param.type.item and param.type.item.kind == "enum":
        values = [v for v in (param.type.item.enum or []) if v is not None]
        value = [values[0]] if values else []
    return value


def argument(param: Param, registry: dict) -> str:
    return py_literal(sample_for(param, registry))


def js_argument(param: Param, registry: dict) -> str:
    return literal(sample_for(param, registry))


def call_arguments(operation: Operation, registry: dict) -> str:
    parts = []
    for param in operation.path_params:
        parts.append(argument(param, registry))
    for param in [*operation.query_params, *operation.body_fields]:
        parts.append(f"{py_param(param.name)}={argument(param, registry)}")
    return ", ".join(parts)


def resolved_path(operation: Operation, registry: dict) -> str:
    path = operation.path
    for param in operation.path_params:
        value = sample_for(param, registry)
        path = path.replace("{" + param.name + "}", str(value))
    return path


def query_keys(operation: Operation) -> list[str]:
    return sorted(p.name for p in operation.query_params)


def wire_value(kind: str, value, lang: str) -> str:
    """One query string value, rendered the way the language's transport sends it."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if kind == "datetime" and lang == "csharp":
        # DateTimeOffset.ToString("o"): seven fractional digits and an offset.
        moment = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        return moment.strftime("%Y-%m-%dT%H:%M:%S.") + f"{moment.microsecond:06d}0+00:00"
    if isinstance(value, float):
        return repr(value)
    return str(value)


def query_values(operation: Operation, registry: dict, lang: str) -> dict[str, list[str]]:
    """The exact query string each parameter of the sample call must produce.

    Asserting the key alone lets a wrongly serialised value through, which is
    how a date rendered in a display format reached the wire unnoticed.
    """
    out: dict[str, list[str]] = {}
    for param in sorted(operation.query_params, key=lambda p: p.name):
        node = param.type
        inner = node.item if node.kind == "array" and node.item else node
        value = sample_for(param, registry)
        items = value if isinstance(value, list) else [value]
        out[param.name] = [wire_value(inner.kind, item, lang) for item in items]
    return out


def body_keys(operation: Operation) -> list[str]:
    return sorted(p.name for p in operation.body_fields)


def python(api: Api, root: Path) -> None:
    models, _ = _registry(api)
    registry = models
    rows, async_rows = [], []
    for operation in sorted(api.operations, key=lambda o: o.operation_id):
        resource, method = operation.operation_id.split(".", 1)
        args = call_arguments(operation, registry)
        row = (
            f'    (\n'
            f'        "{operation.operation_id}",\n'
            f'        "{operation.http_method}",\n'
            f'        "{resolved_path(operation, registry)}",\n'
            f'        {query_values(operation, registry, "python")!r},\n'
            f'        {body_keys(operation)!r},\n'
            f'        "{operation.cardinality}",\n'
            f'        lambda c: c.{resource}.{method}({args}),\n'
            f'    ),'
        )
        rows.append(row)
        async_rows.append(row.replace("lambda c: c.", "lambda c: c."))

    body = PYTHON_TEMPLATE.format(rows="\n".join(rows))
    out = root / "tests" / "test_conformance_generated.py"
    out.write_text(HEADER + body)
    # The language emitter formats its package before this file is written, so
    # the suite has to be formatted here or the lint gate sees drift.
    subprocess.run(
        ["uv", "run", "ruff", "check", "--fix", "--quiet", out.name],
        cwd=out.parent,
        capture_output=True,
    )
    subprocess.run(
        ["uv", "run", "ruff", "format", "--quiet", out.name],
        cwd=out.parent,
        capture_output=True,
    )


def js_call(operation: Operation, registry: dict) -> str:
    """The argument list a generated TypeScript method takes."""
    resource, method = operation.operation_id.split(".", 1)
    args = [js_argument(p, registry) for p in operation.path_params]
    options = [*operation.query_params, *operation.body_fields]
    if options:
        pairs = ", ".join(f"{camel(p.name)}: {js_argument(p, registry)}" for p in options)
        args.append("{ " + pairs + " }")
    return f"c.{camel(resource)}.{camel(method)}({', '.join(args)})"



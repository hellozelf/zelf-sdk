def java_name(raw: str) -> str:
    from naming import camel

    reserved = {"abstract", "assert", "boolean", "break", "byte", "case", "catch", "char",
                "class", "const", "continue", "default", "do", "double", "else", "enum",
                "extends", "final", "finally", "float", "for", "goto", "if", "implements",
                "import", "instanceof", "int", "interface", "long", "native", "new",
                "package", "private", "protected", "public", "return", "short", "static",
                "strictfp", "super", "switch", "synchronized", "this", "throw", "throws",
                "transient", "try", "void", "volatile", "while"}
    out = camel(raw)
    return out + "Value" if out in reserved else out


def _takes_params(operation) -> bool:
    return bool(operation.query_params or operation.body_fields)


def _params_optional(operation) -> bool:
    """A params argument is nullable only when nothing in it is required."""
    return _takes_params(operation) and not any(
        p.required for p in [*operation.query_params, *operation.body_fields]
    )


def java_strings(values: list[str]) -> str:
    if not values:
        return "java.util.List.of()"
    return "java.util.List.of(" + ", ".join(literal(v) for v in values) + ")"


def java_query(values: dict[str, list[str]]) -> str:
    if not values:
        return "java.util.Map.of()"
    entries = ", ".join(
        f"java.util.Map.entry({literal(name)}, {java_strings(rendered)})"
        for name, rendered in values.items()
    )
    return "java.util.Map.ofEntries(" + entries + ")"



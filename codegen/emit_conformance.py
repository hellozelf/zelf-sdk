def java_literal(node, value, registry) -> str:
    """A Java expression for a sample value, matching emit_java's types."""
    kind = node.kind
    if kind == "array":
        if not value:
            return "java.util.List.of()"
        inner = ", ".join(java_literal(node.item, v, registry) for v in value)
        return f"java.util.List.of({inner})"
    if kind == "ref":
        entry = registry.get(node.ref)
        import models as models_module

        if isinstance(entry, models_module.Enum) or entry is None:
            return json.dumps(value if isinstance(value, str) else "")
        return f"json({json.dumps(json.dumps(value))}, {node.ref}.class)"
    if kind == "any":
        return f"json({json.dumps(json.dumps(value))}, JsonNode.class)"
    if kind == "int":
        return f"{value}L"
    if kind == "float":
        return f"{value}d"
    if kind == "bool":
        return "true" if value else "false"
    if isinstance(value, (dict, list)):
        return f"json({json.dumps(json.dumps(value))}, JsonNode.class)"
    return json.dumps(value)



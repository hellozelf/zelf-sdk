    resource = snake(operation.resource)
    method = snake(operation.method)
    params_type = f"{pascal(operation.resource)}{pascal(operation.method)}Params"
    fields = {p.name: sample_for(p, registry)
              for p in [*operation.query_params, *operation.body_fields]}

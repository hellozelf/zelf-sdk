def _registry(api: Api) -> tuple[dict, dict]:
    import models as models_module

    model_list, enum_list = models_module.build(api)
    return (
        {m.name: m for m in model_list} | {e.name: e for e in enum_list},
        {e.name: e for e in enum_list},
    )



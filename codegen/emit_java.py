def one_line(text: str, width: int = 84) -> str:
    flat = " ".join(re.sub(r"`|\*\*", "", text).split())
    sentence = flat.split(". ")[0].rstrip(".")
    return sentence if len(sentence) <= width else textwrap.shorten(sentence, width, placeholder="...")


def javadoc(text: str, indent: str) -> list[str]:
    if not text:
        return []
    flat = re.sub(r"\s*[-*]\s+", "; ", " ".join(text.split())).lstrip("; ")
    flat = flat.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("@", "&#64;")
    lines = textwrap.wrap(flat, 80)
    return [f"{indent}/**"] + [f"{indent} * {line}" for line in lines] + [f"{indent} */"]


def name_of(raw: str) -> str:
    out = camel(raw)
    return out + "Value" if out in RESERVED else out


def java_type(node: Type, enum_names: frozenset[str]) -> str:
    if node.kind in PRIMITIVE:
        return PRIMITIVE[node.kind]
    if node.kind == "enum":
        return "String"
    if node.kind == "ref":
        return "String" if node.ref in enum_names else (node.ref or "JsonNode")
    if node.kind == "array":
        inner = java_type(node.item, enum_names) if node.item else "JsonNode"
        return f"List<{inner}>"
    return "JsonNode"


def model_file(model, enum_names: frozenset[str]) -> str:
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE}.model;",
        "",
        "import com.fasterxml.jackson.annotation.JsonIgnoreProperties;",
        "import com.fasterxml.jackson.annotation.JsonProperty;",
        "import com.fasterxml.jackson.databind.JsonNode;",
        "import java.util.List;",
        "",
    ]
    out += javadoc(model.description or f"The {model.name} object.", "")
    out += ["@JsonIgnoreProperties(ignoreUnknown = true)", f"public record {model.name}("]
    rows = []
    for field in model.fields:
        rendered = java_type(field.type, enum_names)
        rows.append(f'        @JsonProperty("{field.name}") {rendered} {name_of(field.name)}')
    out.append(",\n".join(rows))
    out += [") {", "}", ""]
    return "\n".join(out)


def enum_constants_file(enum) -> str:
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE}.model;",
        "",
        "import java.util.List;",
        "",
    ]
    out += javadoc(enum.description or f"Accepted values for {enum.name}.", "")
    out += [f"public final class {enum.name} {{", "", f"    private {enum.name}() {{", "    }", ""]
    for value in enum.values:
        constant = snake(enum_member(value)).upper()
        out.append(f'    public static final String {constant} = "{value}";')
    out.append("")
    joined = ", ".join(snake(enum_member(v)).upper() for v in enum.values)
    out += [
        "    /** Every value the API accepts here. */",
        f"    public static final List<String> ALL = List.of({joined});",
        "}",
        "",
    ]
    return "\n".join(out)


def exception_file(api: Api) -> str:
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE};",
        "",
        "import com.fasterxml.jackson.databind.JsonNode;",
        "import java.io.IOException;",
        "",
        "/** Base for everything this SDK throws. */",
        "public class ZelfException extends RuntimeException {",
        "",
        "    public ZelfException(String message, Throwable cause) {",
        "        super(message, cause);",
        "    }",
        "",
        "    /** The request never produced an HTTP response. */",
        "    public static class Connection extends ZelfException {",
        "        public Connection(String message, Throwable cause) {",
        '            super("Could not reach the ZelfAI API: " + message, cause);',
        "        }",
        "    }",
        "",
        "    /** The request exceeded the configured timeout. */",
        "    public static final class Timeout extends Connection {",
        "        public Timeout() {",
        '            super("the request timed out", null);',
        "        }",
        "    }",
        "",
        "    /** An error response from the API, with the envelope's own fields. */",
        "    public static class Api extends ZelfException {",
        "",
        "        private final int status;",
        "        private final String code;",
        "        private final JsonNode details;",
        "        private final String logId;",
        "",
        "        public Api(String message, int status, String code, JsonNode details, String logId) {",
        "            super(message, null);",
        "            this.status = status;",
        "            this.code = code;",
        "            this.details = details;",
        "            this.logId = logId;",
        "        }",
        "",
        "        public int status() {",
        "            return status;",
        "        }",
        "",
        "        public String code() {",
        "            return code;",
        "        }",
        "",
        "        public JsonNode details() {",
        "            return details;",
        "        }",
        "",
        "        public String logId() {",
        "            return logId;",
        "        }",
        "",
        "        @Override",
        "        public String toString() {",
        '            String base = status + " " + (code == null ? "" : code) + " " + getMessage();',
        '            return logId == null ? base : base + " (log_id=" + logId + ")";',
        "        }",
        "    }",
        "",
    ]
    for status in sorted(STATUS_CLASS):
        codes = api.error_codes.get(status)
        if codes:
            out += javadoc(", ".join(codes), "    ")
        out += [
            f"    public static final class {STATUS_CLASS[status]} extends Api {{",
            f"        public {STATUS_CLASS[status]}(",
            "                String message, int status, String code, JsonNode details, String logId) {",
            "            super(message, status, code, details, logId);",
            "        }",
            "    }",
            "",
        ]
    out += [
        "    static Api fromResponse(int status, String body) {",
        "        String code = null;",
        "        String logId = null;",
        "        JsonNode details = null;",
        '        String message = "HTTP " + status + " from the ZelfAI API";',
        "        try {",
        "            JsonNode root = Transport.MAPPER.readTree(body);",
        '            if (root.hasNonNull("log_id")) {',
        '                logId = root.get("log_id").asText();',
        "            }",
        '            JsonNode error = root.path("error");',
        "            if (error.isObject()) {",
        '                code = error.path("code").asText(null);',
        '                message = error.path("message").asText(message);',
        '                details = error.path("details");',
        "            }",
        "        } catch (IOException | RuntimeException ignored) {",
        "            // A gateway can answer with HTML; the status alone still classifies it.",
        "        }",
        "        return switch (status) {",
    ]
    for status in sorted(STATUS_CLASS):
        out.append(
            f"            case {status} -> new {STATUS_CLASS[status]}(message, status, code, details, logId);"
        )
    out += [
        "            default -> new Api(message, status, code, details, logId);",
        "        };",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


def error_codes_file(api: Api) -> str:
    every = sorted({c for codes in api.error_codes.values() for c in codes})
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE};",
        "",
        "/** Error codes the API can return in the envelope. */",
        "public final class ZelfErrorCode {",
        "",
        "    private ZelfErrorCode() {",
        "    }",
        "",
    ]
    for code in every:
        out.append(f'    public static final String {code} = "{code}";')
    out += ["}", ""]
    return "\n".join(out)


def params_class(op: Operation, enum_names) -> tuple[str, str]:
    fields = [*op.query_params, *op.body_fields]
    if not fields:
        return "", ""
    name = f"{pascal(op.resource)}{pascal(op.method)}Params"
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE}.resources;",
        "",
        "import com.fasterxml.jackson.annotation.JsonInclude;",
        "import com.fasterxml.jackson.annotation.JsonProperty;",
        "import com.fasterxml.jackson.databind.JsonNode;",
        f"import {PACKAGE}.model.*;",
        "import java.util.List;",
        "",
    ]
    out += javadoc(f"Parameters for {op.operation_id}. Set what you need and leave the rest.", "")
    out += ["@JsonInclude(JsonInclude.Include.NON_NULL)", f"public final class {name} {{", ""]
    for field in fields:
        rendered = java_type(field.type, enum_names)
        out.append(f'    @JsonProperty("{field.name}")')
        out.append(f"    private {rendered} {name_of(field.name)};")
        out.append("")
    for field in fields:
        rendered = java_type(field.type, enum_names)
        accessor = name_of(field.name)
        out += javadoc(one_line(field.description), "    ")
        out += [
            f"    public {name} {accessor}({rendered} value) {{",
            f"        this.{accessor} = value;",
            "        return this;",
            "    }",
            "",
            f"    public {rendered} {accessor}() {{",
            f"        return {accessor};",
            "    }",
            "",
        ]
    out += ["}", ""]
    return name, "\n".join(out)


def query_lines(op: Operation) -> list[str]:
    out = ["        List<Map.Entry<String, String>> query = new ArrayList<>();"]
    for param in op.query_params:
        accessor = name_of(param.name)
        wire = param.name
        if param.type.kind == "array":
            out += [
                f"        if (parameters.{accessor}() != null) {{",
                f"            for (Object item : parameters.{accessor}()) {{",
                f'                query.add(Map.entry("{wire}", String.valueOf(item)));',
                "            }",
                "        }",
            ]
        else:
            out += [
                f"        if (parameters.{accessor}() != null) {{",
                f'            query.add(Map.entry("{wire}", String.valueOf(parameters.{accessor}())));',
                "        }",
            ]
    return out


def method(op: Operation, params_name: str) -> str:
    item = f"{op.item}.class" if op.item else "JsonNode.class"
    item_type = op.item or "JsonNode"
    body_text = re.sub(r"^`[a-z_.]+`\n\n", "", op.description).split("\n\n**Examples**")[0]

    args = [f"String {name_of(p.name)}" for p in op.path_params]
    if params_name:
        args.append(f"{params_name} parameters")

    if op.returns_nothing:
        returns = "void"
    elif op.cardinality == "page":
        returns = f"Page<{item_type}>"
    elif op.cardinality == "list":
        returns = f"List<{item_type}>"
    else:
        returns = item_type

    out = javadoc(f"{op.summary}. {body_text}", "    ")
    out.append(f"    /** @see <a href=\"#\">{op.http_method} {op.path} ({op.operation_id})</a> */")
    out = javadoc(
        f"{op.summary}. {body_text} Calls {op.http_method} {op.path} ({op.operation_id}).", "    "
    )
    out.append(f"    public {returns} {name_of(op.method)}({', '.join(args)}) {{")
    if params_name:
        out.append(f"        if (parameters == null) {{")
        out.append(f"            parameters = new {params_name}();")
        out.append("        }")
    if op.path_params:
        pairs = ", ".join(f'"{p.name}", {name_of(p.name)}' for p in op.path_params)
        out.append(
            f'        String path = Transport.resolvePath("{op.path}", Map.of({pairs}));'
        )
    else:
        out.append(f'        String path = "{op.path}";')
    out += query_lines(op) if op.query_params else [
        "        List<Map.Entry<String, String>> query = new ArrayList<>();"
    ]
    body_arg = "parameters" if op.body_fields else "null"
    out.append(
        f'        Envelope<{item_type}> envelope = transport.send("{op.http_method}", path, query, '
        f"{body_arg}, {item});"
    )
    if op.returns_nothing:
        pass
    elif op.cardinality == "page":
        out.append(f"        return new Page<>(envelope, transport, path, query, {item});")
    elif op.cardinality == "list":
        out.append("        return envelope.results();")
    else:
        out += [
            "        if (envelope.results().isEmpty()) {",
            "            throw new ZelfException.NotFound(",
            f'                    "No {op.item} matched the request.", 404, "NOT_FOUND", null,',
            "                    envelope.logId());",
            "        }",
            "        return envelope.results().get(0);",
        ]
    out.append("    }")
    return "\n".join(out)


def resource_file(resource: str, ops: list[Operation]) -> str:
    name = f"{pascal(resource)}Resource"
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE}.resources;",
        "",
        "import com.fasterxml.jackson.databind.JsonNode;",
        f"import {PACKAGE}.Envelope;",
        f"import {PACKAGE}.Page;",
        f"import {PACKAGE}.Transport;",
        f"import {PACKAGE}.ZelfException;",
        f"import {PACKAGE}.model.*;",
        "import java.util.ArrayList;",
        "import java.util.List;",
        "import java.util.Map;",
        "",
        f"/** The {resource} endpoints. */",
        f"public final class {name} {{",
        "",
        "    private final Transport transport;",
        "",
        f"    public {name}(Transport transport) {{",
        "        this.transport = transport;",
        "    }",
        "",
    ]
    out.append("\n\n".join(method(op, params_class(op, frozenset())[0]) for op in sorted(ops, key=lambda o: o.method)))
    out += ["}", ""]
    return "\n".join(out)


def event_type_file(api: Api) -> str:
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE}.webhooks;",
        "",
        "import java.util.List;",
        "import java.util.Map;",
        "import java.util.stream.Collectors;",
        "",
        "/** An event the API can deliver, one per webhooks declaration in the spec. */",
        "public enum EventType {",
        "",
    ]
    rows = []
    for event in api.webhooks:
        doc = javadoc(one_line(event.description), "    ")
        rows.append("\n".join(doc + [f'    {snake(event.event_type).upper()}("{event.event_type}")']))
    out.append(",\n\n".join(rows) + ";")
    out += [
        "",
        "    private static final Map<String, EventType> BY_WIRE =",
        "            List.of(values()).stream().collect(Collectors.toMap(EventType::wire, value -> value));",
        "",
        "    private final String wire;",
        "",
        "    EventType(String wire) {",
        "        this.wire = wire;",
        "    }",
        "",
        "    /** The wire value. */",
        "    public String wire() {",
        "        return wire;",
        "    }",
        "",
        "    /** The declared event type, or null for one this SDK predates. */",
        "    public static EventType fromWire(String value) {",
        "        return BY_WIRE.get(value);",
        "    }",
        "",
        "    @Override",
        "    public String toString() {",
        "        return wire;",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


def client_file(api: Api) -> str:
    resources = sorted(api.resources)
    out = [
        HEADER.rstrip(),
        f"package {PACKAGE};",
        "",
    ]
    for res in resources:
        out.append(f"import {PACKAGE}.resources.{pascal(res)}Resource;")
    out += [
        "",
        f"/** Client for the {api.title}. */",
        "public final class ZelfClient {",
        "",
        "    /** The SDK version sent in the User-Agent header. */",
        '    public static final String VERSION = "' + VERSION + '";',
        "",
        "    private final Transport transport;",
        "",
    ]
    for res in resources:
        out.append(f"    private final {pascal(res)}Resource {name_of(res)};")
    out += [
        "",
        "    public ZelfClient(ZelfClientOptions options) {",
        "        this.transport = new Transport(options);",
    ]
    for res in resources:
        out.append(f"        this.{name_of(res)} = new {pascal(res)}Resource(transport);")
    out += [
        "    }",
        "",
        "    public ZelfClient(String apiKey) {",
        "        this(ZelfClientOptions.builder().apiKey(apiKey));",
        "    }",
        "",
    ]
    for res in resources:
        out += [
            f"    /** The {res} endpoints. */",
            f"    public {pascal(res)}Resource {name_of(res)}() {{",
            f"        return {name_of(res)};",
            "    }",
            "",
        ]
    out += [
        "    /** The endpoint this client talks to. */",
        "    public String baseUrl() {",
        "        return transport.baseUrl();",
        "    }",
        "",
        "    /** Never prints the key. */",
        "    @Override",
        "    public String toString() {",
        '        return "ZelfClient(baseUrl=" + baseUrl() + ", apiKey=***)";',
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)



def emit(api: Api, spec_path: Path, root: Path, templates: Path) -> None:
    main = root.joinpath("src", "main", "java", *PACKAGE_PATH)
    if main.exists():
        shutil.rmtree(main)
    (main / "model").mkdir(parents=True)
    (main / "resources").mkdir()
    (main / "webhooks").mkdir()

    for name in ("Transport.java", "Envelope.java", "ZelfClientOptions.java", "Page.java", "PageLimits.java"):
        shutil.copyfile(templates.joinpath(*PACKAGE_PATH, name), main / name)
    for name in ("Webhook.java", "WebhookEvent.java", "WebhookHandler.java"):
        shutil.copyfile(templates.joinpath(*PACKAGE_PATH, "webhooks", name), main / "webhooks" / name)

    found, enums = model_ir.build(api)
    enum_names = frozenset(e.name for e in enums)
    for model in found:
        (main / "model" / f"{model.name}.java").write_text(model_file(model, enum_names))
    for enum in enums:
        (main / "model" / f"{enum.name}.java").write_text(enum_constants_file(enum))

    (main / "ZelfException.java").write_text(exception_file(api))
    (main / "ZelfErrorCode.java").write_text(error_codes_file(api))
    (main / "webhooks" / "EventType.java").write_text(event_type_file(api))

    for resource, ops in sorted(api.resources.items()):
        for op in ops:
            name, declaration = params_class(op, enum_names)
            if declaration:
                (main / "resources" / f"{name}.java").write_text(declaration)
        (main / "resources" / f"{pascal(resource)}Resource.java").write_text(
            resource_file(resource, ops)
        )
    (main / "ZelfClient.java").write_text(client_file(api))
    (root / "pom.xml").write_text(POM.format(title=api.title, version=VERSION))
